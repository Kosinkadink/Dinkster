def euler(
    *,
    s_churn: float = 0.0,
    s_tmin: float = 0.0,
    s_tmax: float = math.inf,
    s_noise: float = 1.0,
) -> StepBeginSolverFn[Any]:
    """Karras Algorithm 2 Euler steps (sample_euler @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            gamma = _churn_gamma(sigmas[i], n, s_churn=s_churn, s_tmin=s_tmin, s_tmax=s_tmax)
            sigma_hat = sigmas[i] * (gamma + 1.0)
            if gamma > 0:
                eps = _require_noise(noise, "euler with s_churn > 0")(sigmas[i], sigmas[i + 1])
                x = x + eps * (s_noise * math.sqrt(sigma_hat**2 - sigmas[i] ** 2))
            denoised = denoiser(x, sigma_hat)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            d = _to_d(x, sigma_hat, denoised)
            x = x + d * (sigmas[i + 1] - sigma_hat)
        return x

    return solve


def _check_ancestral_eta(eta: float) -> None:
    """The ancestral solvers' supported eta domain is [0, 1]: the RF/flow
    variants divide by the downstep sigma (and take its log), which
    eta > 1 drives to zero or negative on ordinary schedules - the
    reference produces NaNs there, the port refuses. Mirrors the
    _ANCESTRAL_OPTIONS bounds for direct factory callers."""
    if not 0.0 <= eta <= 1.0:
        raise ValueError(f"eta must be in [0, 1], got {eta}")


class _DPMSolver:
    """Torch-free DPMSolver and PID math from k_diffusion @ b78cec87."""

    def __init__(self, denoiser: Denoiser[Any]) -> None:
        self.denoiser = denoiser

    @staticmethod
    def sigma(t: float) -> float:
        return math.exp(-t)

    def eps(self, cache: dict[str, TensorT], key: str, x: TensorT, t: float) -> TensorT:
        if key not in cache:
            sigma = self.sigma(t)
            cache[key] = (x - self.denoiser(x, sigma)) * (1.0 / sigma)
        return cache[key]

    def step1(self, x: TensorT, t: float, tn: float, cache: dict[str, TensorT]) -> TensorT:
        h = tn - t
        return x - self.eps(cache, "eps", x, t) * (self.sigma(tn) * math.expm1(h))

    def step2(
        self, x: TensorT, t: float, tn: float, cache: dict[str, TensorT], r1: float = 0.5
    ) -> TensorT:
        h = tn - t
        eps = self.eps(cache, "eps", x, t)
        s1 = t + r1 * h
        u1 = x - eps * (self.sigma(s1) * math.expm1(r1 * h))
        er1 = self.eps(cache, "eps_r1", u1, s1)
        return (
            x
            - eps * (self.sigma(tn) * math.expm1(h))
            - (er1 - eps) * (self.sigma(tn) / (2 * r1) * math.expm1(h))
        )

    def step3(self, x: TensorT, t: float, tn: float, cache: dict[str, TensorT]) -> TensorT:
        h, r1, r2 = tn - t, 1 / 3, 2 / 3
        eps = self.eps(cache, "eps", x, t)
        s1, s2 = t + r1 * h, t + r2 * h
        u1 = x - eps * (self.sigma(s1) * math.expm1(r1 * h))
        er1 = self.eps(cache, "eps_r1", u1, s1)
        if r2 * h == 0 or h == 0:
            raise ValueError("dpm solver degenerate interval: repeated transformed time")
        u2 = (
            x
            - eps * (self.sigma(s2) * math.expm1(r2 * h))
            - (er1 - eps) * (self.sigma(s2) * (r2 / r1) * (math.expm1(r2 * h) / (r2 * h) - 1))
        )
        er2 = self.eps(cache, "eps_r2", u2, s2)
        return (
            x
            - eps * (self.sigma(tn) * math.expm1(h))
            - (er2 - eps) * (self.sigma(tn) / r2 * (math.expm1(h) / h - 1))
        )


class _PID:
    def __init__(
        self, h: float, p: float, i: float, d: float, order: float, accept_safety: float
    ) -> None:
        self.h = h
        self.b1, self.b2, self.b3 = (p + i + d) / order, -(p + 2 * d) / order, d / order
        self.accept_safety = accept_safety
        self.errs: list[float] = []

    def propose(self, error: float) -> bool:
        inv = 1 / (error + 1e-8)
        if not self.errs:
            self.errs = [inv, inv, inv]
        self.errs[0] = inv
        factor = self.errs[0] ** self.b1 * self.errs[1] ** self.b2 * self.errs[2] ** self.b3
        factor = 1 + math.atan(factor - 1)
        accept = factor >= self.accept_safety
        if accept:
            self.errs[2], self.errs[1] = self.errs[1], self.errs[0]
        self.h *= factor
        return accept


def _dpm_bounds(sigmas: Sequence[float], what: str) -> tuple[float, float, int]:
    if len(sigmas) <= 1:
        return 0.0, 0.0, 0
    sigma_max = sigmas[0]
    sigma_min = sigmas[-2] if sigmas[-1] == 0 else sigmas[-1]
    if sigma_min <= 0 or sigma_max <= 0:
        raise ValueError(f"{what} degenerate schedule: sigma_min and sigma_max must be positive")
    return sigma_min, sigma_max, len(sigmas) - 1


def dpm_fast(*, eta: float = 0.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """DPM-Solver-Fast plus ComfyUI's non-sigmas KSAMPLER adaptation."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        sigma_min, sigma_max, nfe = _dpm_bounds(sigmas, "dpm_fast")
        if nfe == 0:
            return x
        ts0, tse = -math.log(sigma_max), -math.log(sigma_min)
        if tse <= ts0 and eta:
            raise ValueError("dpm_fast reverse sampling requires eta=0")
        m = math.floor(nfe / 3) + 1
        ts = [ts0 + (tse - ts0) * j / m for j in range(m + 1)]
        orders = ([3] * (m - 2) + [2, 1]) if nfe % 3 == 0 else ([3] * (m - 1) + [nfe % 3])
        dpm = _DPMSolver(denoiser)
        for j, order in enumerate(orders):
            t, tn = ts[j], ts[j + 1]
            su = 0.0
            if eta:
                sd, _ = _ancestral_step(dpm.sigma(t), dpm.sigma(tn), eta)
                tn2 = min(tse, -math.log(sd))
                su = math.sqrt(max(dpm.sigma(tn) ** 2 - dpm.sigma(tn2) ** 2, 0.0))
            else:
                tn2 = tn
            cache: dict[str, TensorT] = {}
            eps = dpm.eps(cache, "eps", x, t)
            _emit(
                on_step,
                info,
                j,
                len(sigmas) - 1,
                dpm.sigma(t),
                x,
                x - eps * dpm.sigma(t),
            )
            x = (dpm.step1 if order == 1 else dpm.step2 if order == 2 else dpm.step3)(
                x, t, tn2, cache
            )
            if su * s_noise != 0:
                x = x + _require_noise(noise, "dpm_fast")(dpm.sigma(t), dpm.sigma(tn)) * (
                    su * s_noise
                )
        return x

    return solve


def dpm_adaptive(
    *,
    order: int = 3,
    rtol: float = 0.05,
    atol: float = 0.0078,
    h_init: float = 0.05,
    pcoeff: float = 0.0,
    icoeff: float = 1.0,
    dcoeff: float = 0.0,
    accept_safety: float = 0.81,
    eta: float = 0.0,
    s_noise: float = 1.0,
) -> SolverFn[Any]:
    """DPM-Solver-12/23 adaptive plus ComfyUI's KSAMPLER adaptation."""
    if order not in {2, 3}:
        raise ValueError(f"dpm_adaptive order must be 2 or 3, got {order}")
    if not math.isfinite(eta) or not 0.0 <= eta <= 100.0:
        raise ValueError(f"dpm_adaptive eta must be in [0, 100], got {eta}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        sigma_min, sigma_max, _ = _dpm_bounds(sigmas, "dpm_adaptive")
        if len(sigmas) <= 1:
            return x
        start, end = -math.log(sigma_max), -math.log(sigma_min)
        forward = end > start
        if not forward and eta:
            raise ValueError("dpm_adaptive reverse sampling requires eta=0")
        pid = _PID(
            abs(h_init) * (1 if forward else -1),
            pcoeff,
            icoeff,
            dcoeff,
            1.5 if eta else order,
            accept_safety,
        )
        # ComfyUI stores both tolerances in float32. Apply that rounding only
        # above 1 so the established eta <= 1 scalar identity remains stable.
        effective_rtol = struct.unpack("!f", struct.pack("!f", rtol))[0] if eta > 1.0 else rtol
        effective_atol = struct.unpack("!f", struct.pack("!f", atol))[0] if eta > 1.0 else atol
        dpm, s, x_prev, attempts = _DPMSolver(denoiser), start, x, 0
        while s < end - 1e-5 if forward else s > end + 1e-5:
            previous_s = s
            t = min(end, s + pid.h) if forward else max(end, s + pid.h)
            su = 0.0
            if eta:
                sd, _ = _ancestral_step(dpm.sigma(s), dpm.sigma(t), eta)
                t2 = end if sd == 0 else min(end, -math.log(sd))
                su = math.sqrt(max(dpm.sigma(t) ** 2 - dpm.sigma(t2) ** 2, 0.0))
            else:
                t2 = t
            cache: dict[str, TensorT] = {}
            callback_x = x
            callback_sigma = dpm.sigma(s)
            callback_eps = dpm.eps(cache, "eps", x, s)
            if order == 2:
                low, high = dpm.step1(x, s, t2, cache), dpm.step2(x, s, t2, cache)
            else:
                low, high = dpm.step2(x, s, t2, cache, 1 / 3), dpm.step3(x, s, t2, cache)
            # The runtime checks justify preserving the solver's concrete
            # tensor type while exposing only this solver's extra operations.
            low_ops = _adaptive_ops(low)
            previous_ops = _adaptive_ops(x_prev)
            x_ops = _adaptive_ops(x)
            delta = _adaptive_ops(low_ops.abs()).maximum(previous_ops.abs()) * effective_rtol
            delta = _adaptive_ops(delta).clamp(effective_atol, math.inf)
            scaled = _adaptive_ops(low - high) / delta
            squared_ops = _adaptive_ops(scaled * scaled)
            error = math.sqrt(float(squared_ops.sum())) / math.sqrt(x_ops.numel())
            accepted = pid.propose(error)
            if accepted:
                x_prev, x, s = low, high, t
                coefficient = su * s_noise
                if coefficient != 0:
                    x = (
                        x
                        + _require_noise(noise, "dpm_adaptive")(dpm.sigma(previous_s), dpm.sigma(t))
                        * coefficient
                    )
            _emit(
                on_step,
                info,
                attempts,
                len(sigmas) - 1,
                callback_sigma,
                callback_x,
                callback_x - callback_eps * callback_sigma,
            )
            attempts += 1
        return x

    return solve


def euler_ancestral(*, eta: float = 1.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """Ancestral Euler (sample_euler_ancestral @ b78cec87), including the
    reference's dispatch to the RF variant for flow/CONST models."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if is_flow_parameterization(info.parameterization):
            return _euler_ancestral_rf(
                denoiser,
                x,
                sigmas,
                info,
                eta=eta,
                s_noise=s_noise,
                noise=noise,
                on_step=on_step,
                on_step_begin=on_step_begin,
            )
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            sigma_down, sigma_up = _ancestral_step(sigmas[i], sigmas[i + 1], eta)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigma_down == 0:
                x = denoised
            else:
                d = _to_d(x, sigmas[i], denoised)
                x = x + d * (sigma_down - sigmas[i])
                coeff = s_noise * sigma_up
                if coeff != 0.0:
                    x = (
                        x
                        + _require_noise(noise, "euler_ancestral")(sigmas[i], sigmas[i + 1]) * coeff
                    )
        return x

    return solve


def _euler_ancestral_rf(
    denoiser: Denoiser[TensorT],
    x: TensorT,
    sigmas: Sequence[float],
    info: SamplerInfo,
    *,
    eta: float,
    s_noise: float,
    noise: NoiseSampler[TensorT] | None,
    on_step: StepCallback | None,
    on_step_begin: Callable[[int], None] | None = None,
) -> TensorT:
    """sample_euler_ancestral_RF @ b78cec87."""
    s_noise_eff = s_noise * info.noise_scale
    n = len(sigmas) - 1
    for i in range(n):
        _begin(on_step_begin, i)
        denoised = denoiser(x, sigmas[i])
        _emit(on_step, info, i, n, sigmas[i], x, denoised)
        if sigmas[i + 1] == 0:
            x = denoised
        else:
            downstep_ratio = 1.0 + (sigmas[i + 1] / sigmas[i] - 1.0) * eta
            sigma_down = sigmas[i + 1] * downstep_ratio
            alpha_ip1 = 1.0 - sigmas[i + 1]
            alpha_down = 1.0 - sigma_down
            renoise_coeff = math.sqrt(
                max(sigmas[i + 1] ** 2 - sigma_down**2 * alpha_ip1**2 / alpha_down**2, 0.0)
            )
            ratio = sigma_down / sigmas[i]
            x = x * ratio + denoised * (1.0 - ratio)
            if eta > 0:
                x = x * (alpha_ip1 / alpha_down)
                coeff = s_noise_eff * renoise_coeff
                if coeff != 0.0:
                    x = (
                        x
                        + _require_noise(noise, "euler_ancestral (flow)")(sigmas[i], sigmas[i + 1])
                        * coeff
                    )
    return x


def euler_ancestral_cfg_pp(
    *,
    eta: float = 1.0,
    s_noise: float = 1.0,
    _what: str = "euler_ancestral_cfg_pp",
) -> SolverFn[Any]:
    """Ancestral Euler, CFG++ (sample_euler_ancestral_cfg_pp
    @ b78cec87): the guided update rides the UNCONDITIONED derivative
    while the denoised anchor stays CFG-combined. Flow-general through
    half-logSNR alphas rather than a separate RF dispatch - the
    reference has none. s_noise is scaled by info.noise_scale for
    every parameterization (the reference's model_sampling probe).

    Flow schedules must start below sigma 1.0: alpha there is 0 and
    the reference cascades NaNs where this port raises (math.log(0))
    - the same unsupported-input stance as eta > 1."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        pair = _require_uncond(denoiser, _what)
        flow = is_flow_parameterization(info.parameterization)
        s_noise_eff = s_noise * info.noise_scale
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised, uncond_denoised = pair.call_with_uncond(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                alpha_s = _alpha(sigmas[i], _half_log_snr(sigmas[i], flow=flow))
                alpha_t = _alpha(sigmas[i + 1], _half_log_snr(sigmas[i + 1], flow=flow))
                d = _to_d(x, sigmas[i], uncond_denoised * alpha_s)  # to noise
                # DDIM stochastic sampling over sigma/alpha ratios
                sigma_down, sigma_up = _ancestral_step(
                    sigmas[i] / alpha_s, sigmas[i + 1] / alpha_t, eta
                )
                sigma_down = alpha_t * sigma_down
                # Euler method
                x = denoised * alpha_t + d * sigma_down
                if eta > 0 and s_noise_eff > 0:
                    coeff = alpha_t * s_noise_eff * sigma_up
                    if coeff != 0.0:
                        x = x + _require_noise(noise, _what)(sigmas[i], sigmas[i + 1]) * coeff
        return x

    return solve


def euler_cfg_pp() -> SolverFn[Any]:
    """Euler, CFG++ (sample_euler_cfg_pp @ b78cec87): exactly the
    ancestral CFG++ solver at eta 0 and s_noise 0 - the reference is
    the same delegation - so it is fully deterministic. _what makes
    the capability refusal name this solver, not the delegate."""
    return euler_ancestral_cfg_pp(eta=0.0, s_noise=0.0, _what="euler_cfg_pp")


def cfgpp_ud10_ab() -> SolverFn[Any]:
    """CFG++ Euler with UD10 unconditioned and AB2 derivative history."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        pair = _require_uncond(denoiser, "cfgpp_ud10_ab")
        flow = is_flow_parameterization(info.parameterization)
        derivatives: list[TensorT] = []
        denoised_history: list[TensorT] = []
        old_uncond_d: TensorT | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised, uncond_denoised = pair.call_with_uncond(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            alpha_s = _alpha(sigmas[i], _half_log_snr(sigmas[i], flow=flow))
            alpha_t = (
                1.0
                if sigmas[i + 1] == 0.0
                else _alpha(sigmas[i + 1], _half_log_snr(sigmas[i + 1], flow=flow))
            )
            current_uncond_d = _to_d(x, sigmas[i], uncond_denoised * alpha_s)
            uncond_d = current_uncond_d
            dt = sigmas[i + 1] - sigmas[i]
            if dt == 0.0:
                raise ValueError("cfgpp_ud10_ab degenerate schedule: repeated sigma")
            if i > 0:
                assert old_uncond_d is not None
                previous_dt = sigmas[i] - sigmas[i - 1]
                if previous_dt == 0.0:
                    raise ValueError("cfgpp_ud10_ab degenerate schedule: repeated sigma")
                step_ratio = dt / previous_dt
                uncond_d = uncond_d + (current_uncond_d - old_uncond_d) * (0.1 * step_ratio)
            euler_step = denoised * alpha_t + uncond_d * sigmas[i + 1] - x
            derivative = euler_step * (1.0 / dt)
            derivatives.append(derivative)
            if len(derivatives) > 2:
                derivatives.pop(0)
            if len(derivatives) == 1:
                step = euler_step
            else:
                history_step = derivatives[-1] * _lms_coeff(2, sigmas, i, 0)
                history_step = history_step + derivatives[-2] * _lms_coeff(2, sigmas, i, 1)
                step = euler_step + (history_step - euler_step) * 0.25
            x = x + step
            if sigmas[i + 1] == 0.0 and denoised_history:
                denoised_slope = (denoised - denoised_history[-1]) * (
                    1.0 / (sigmas[i] - sigmas[i - 1])
                )
                x = denoised - denoised_slope * sigmas[i]
            denoised_history.append(denoised)
            if len(denoised_history) > 2:
                denoised_history.pop(0)
            old_uncond_d = current_uncond_d
        return x

    return solve


def heun(
    *,
    s_churn: float = 0.0,
    s_tmin: float = 0.0,
    s_tmax: float = math.inf,
    s_noise: float = 1.0,
) -> SolverFn[Any]:
    """Karras Algorithm 2 Heun steps (sample_heun @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            gamma = _churn_gamma(sigmas[i], n, s_churn=s_churn, s_tmin=s_tmin, s_tmax=s_tmax)
            sigma_hat = sigmas[i] * (gamma + 1.0)
            if gamma > 0:
                eps = _require_noise(noise, "heun with s_churn > 0")(sigmas[i], sigmas[i + 1])
                x = x + eps * (s_noise * math.sqrt(sigma_hat**2 - sigmas[i] ** 2))
            denoised = denoiser(x, sigma_hat)
            d = _to_d(x, sigma_hat, denoised)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            dt = sigmas[i + 1] - sigma_hat
            if sigmas[i + 1] == 0:
                x = x + d * dt
            else:
                x_2 = x + d * dt
                denoised_2 = denoiser(x_2, sigmas[i + 1])
                d_2 = _to_d(x_2, sigmas[i + 1], denoised_2)
                x = x + (d + d_2) * (0.5 * dt)
        return x

    return solve


def dpm_2(
    *,
    s_churn: float = 0.0,
    s_tmin: float = 0.0,
    s_tmax: float = math.inf,
    s_noise: float = 1.0,
) -> SolverFn[Any]:
    """DPM-Solver-2 with Karras churn (sample_dpm_2 @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            gamma = _churn_gamma(sigmas[i], n, s_churn=s_churn, s_tmin=s_tmin, s_tmax=s_tmax)
            sigma_hat = sigmas[i] * (gamma + 1.0)
            if gamma > 0:
                eps = _require_noise(noise, "dpm_2 with s_churn > 0")(sigmas[i], sigmas[i + 1])
                x = x + eps * (s_noise * math.sqrt(sigma_hat**2 - sigmas[i] ** 2))
            denoised = denoiser(x, sigma_hat)
            d = _to_d(x, sigma_hat, denoised)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = x + d * (sigmas[i + 1] - sigma_hat)
            else:
                # log-space midpoint, written as the reference's lerp
                log_hat = math.log(sigma_hat)
                sigma_mid = math.exp(log_hat + (math.log(sigmas[i + 1]) - log_hat) * 0.5)
                x_2 = x + d * (sigma_mid - sigma_hat)
                denoised_2 = denoiser(x_2, sigma_mid)
                d_2 = _to_d(x_2, sigma_mid, denoised_2)
                x = x + d_2 * (sigmas[i + 1] - sigma_hat)
        return x

    return solve


def dpm_2_ancestral(*, eta: float = 1.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """Ancestral DPM-Solver-2 (sample_dpm_2_ancestral @ b78cec87),
    including the RF dispatch for flow/CONST models."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if is_flow_parameterization(info.parameterization):
            return _dpm_2_ancestral_rf(
                denoiser,
                x,
                sigmas,
                info,
                eta=eta,
                s_noise=s_noise,
                noise=noise,
                on_step=on_step,
                on_step_begin=on_step_begin,
            )
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            sigma_down, sigma_up = _ancestral_step(sigmas[i], sigmas[i + 1], eta)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            d = _to_d(x, sigmas[i], denoised)
            if sigma_down == 0:
                x = x + d * (sigma_down - sigmas[i])
            else:
                log_s = math.log(sigmas[i])
                sigma_mid = math.exp(log_s + (math.log(sigma_down) - log_s) * 0.5)
                x_2 = x + d * (sigma_mid - sigmas[i])
                denoised_2 = denoiser(x_2, sigma_mid)
                d_2 = _to_d(x_2, sigma_mid, denoised_2)
                x = x + d_2 * (sigma_down - sigmas[i])
                coeff = s_noise * sigma_up
                if coeff != 0.0:
                    x = (
                        x
                        + _require_noise(noise, "dpm_2_ancestral")(sigmas[i], sigmas[i + 1]) * coeff
                    )
        return x

    return solve


def _dpm_2_ancestral_rf(
    denoiser: Denoiser[TensorT],
    x: TensorT,
    sigmas: Sequence[float],
    info: SamplerInfo,
    *,
    eta: float,
    s_noise: float,
    noise: NoiseSampler[TensorT] | None,
    on_step: StepCallback | None,
    on_step_begin: Callable[[int], None] | None = None,
) -> TensorT:
    """sample_dpm_2_ancestral_RF @ b78cec87."""
    s_noise_eff = s_noise * info.noise_scale
    n = len(sigmas) - 1
    for i in range(n):
        _begin(on_step_begin, i)
        denoised = denoiser(x, sigmas[i])
        downstep_ratio = 1.0 + (sigmas[i + 1] / sigmas[i] - 1.0) * eta
        sigma_down = sigmas[i + 1] * downstep_ratio
        alpha_ip1 = 1.0 - sigmas[i + 1]
        alpha_down = 1.0 - sigma_down
        renoise_coeff = math.sqrt(
            max(sigmas[i + 1] ** 2 - sigma_down**2 * alpha_ip1**2 / alpha_down**2, 0.0)
        )
        _emit(on_step, info, i, n, sigmas[i], x, denoised)
        d = _to_d(x, sigmas[i], denoised)
        if sigma_down == 0:
            x = x + d * (sigma_down - sigmas[i])
        else:
            log_s = math.log(sigmas[i])
            sigma_mid = math.exp(log_s + (math.log(sigma_down) - log_s) * 0.5)
            x_2 = x + d * (sigma_mid - sigmas[i])
            denoised_2 = denoiser(x_2, sigma_mid)
            d_2 = _to_d(x_2, sigma_mid, denoised_2)
            x = x + d_2 * (sigma_down - sigmas[i])
            x = x * (alpha_ip1 / alpha_down)
            coeff = s_noise_eff * renoise_coeff
            if coeff != 0.0:
                x = (
                    x
                    + _require_noise(noise, "dpm_2_ancestral (flow)")(sigmas[i], sigmas[i + 1])
                    * coeff
                )
    return x


def dpmpp_2s_ancestral(*, eta: float = 1.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """Ancestral DPM-Solver++(2S) (sample_dpmpp_2s_ancestral @ b78cec87),
    including the RF dispatch for flow/CONST models."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if is_flow_parameterization(info.parameterization):
            return _dpmpp_2s_ancestral_rf(
                denoiser,
                x,
                sigmas,
                info,
                eta=eta,
                s_noise=s_noise,
                noise=noise,
                on_step=on_step,
                on_step_begin=on_step_begin,
            )
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            sigma_down, sigma_up = _ancestral_step(sigmas[i], sigmas[i + 1], eta)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigma_down == 0:
                d = _to_d(x, sigmas[i], denoised)
                x = x + d * (sigma_down - sigmas[i])
            else:
                # t-space: t = -log(sigma), sigma_fn(t) = exp(-t)
                t = -math.log(sigmas[i])
                t_next = -math.log(sigma_down)
                r = 1.0 / 2.0
                h = t_next - t
                s = t + r * h
                x_2 = x * (math.exp(-s) / sigmas[i]) - denoised * math.expm1(-h * r)
                denoised_2 = denoiser(x_2, math.exp(-s))
                x = x * (sigma_down / sigmas[i]) - denoised_2 * math.expm1(-h)
            if sigmas[i + 1] > 0:
                coeff = s_noise * sigma_up
                if coeff != 0.0:
                    x = (
                        x
                        + _require_noise(noise, "dpmpp_2s_ancestral")(sigmas[i], sigmas[i + 1])
                        * coeff
                    )
        return x

    return solve


def _dpmpp_2s_ancestral_rf(
    denoiser: Denoiser[TensorT],
    x: TensorT,
    sigmas: Sequence[float],
    info: SamplerInfo,
    *,
    eta: float,
    s_noise: float,
    noise: NoiseSampler[TensorT] | None,
    on_step: StepCallback | None,
    on_step_begin: Callable[[int], None] | None = None,
) -> TensorT:
    """sample_dpmpp_2s_ancestral_RF @ b78cec87 (logit-space lambdas)."""
    s_noise_eff = s_noise * info.noise_scale
    n = len(sigmas) - 1
    for i in range(n):
        _begin(on_step_begin, i)
        denoised = denoiser(x, sigmas[i])
        downstep_ratio = 1.0 + (sigmas[i + 1] / sigmas[i] - 1.0) * eta
        sigma_down = sigmas[i + 1] * downstep_ratio
        alpha_ip1 = 1.0 - sigmas[i + 1]
        alpha_down = 1.0 - sigma_down
        renoise_coeff = math.sqrt(
            max(sigmas[i + 1] ** 2 - sigma_down**2 * alpha_ip1**2 / alpha_down**2, 0.0)
        )
        _emit(on_step, info, i, n, sigmas[i], x, denoised)
        if sigmas[i + 1] == 0:
            d = _to_d(x, sigmas[i], denoised)
            x = x + d * (sigma_down - sigmas[i])
        else:
            # lambda = log((1 - sigma) / sigma); sigma_fn = 1 / (exp(l) + 1)
            if sigmas[i] == 1.0:
                sigma_s = 0.9999
            else:
                t_i = math.log((1.0 - sigmas[i]) / sigmas[i])
                t_down = math.log((1.0 - sigma_down) / sigma_down)
                s = t_i + 0.5 * (t_down - t_i)
                sigma_s = 1.0 / (math.exp(s) + 1.0)
            sigma_s_ratio = sigma_s / sigmas[i]
            u = x * sigma_s_ratio + denoised * (1.0 - sigma_s_ratio)
            denoised_2 = denoiser(u, sigma_s)
            sigma_down_ratio = sigma_down / sigmas[i]
            x = x * sigma_down_ratio + denoised_2 * (1.0 - sigma_down_ratio)
        if sigmas[i + 1] > 0 and eta > 0:
            x = x * (alpha_ip1 / alpha_down)
            coeff = s_noise_eff * renoise_coeff
            if coeff != 0.0:
                x = (
                    x
                    + _require_noise(noise, "dpmpp_2s_ancestral (flow)")(sigmas[i], sigmas[i + 1])
                    * coeff
                )
    return x


def dpmpp_2s_ancestral_cfg_pp(*, eta: float = 1.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """Ancestral DPM-Solver++(2S), CFG++
    (sample_dpmpp_2s_ancestral_cfg_pp @ b78cec87). No RF dispatch: the
    reference runs this same t-space math for flow models too. Two
    denoiser calls per full step; the reference's post-CFG hook
    OVERWRITES its captured uncond at the midpoint call, so the final
    update deliberately mixes the first call's denoised with the
    SECOND call's uncond - transcribed exactly, quirk included.
    s_noise is scaled by info.noise_scale (the reference's
    model_sampling probe)."""
    _check_ancestral_eta(eta)

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        pair = _require_uncond(denoiser, "dpmpp_2s_ancestral_cfg_pp")
        s_noise_eff = s_noise * info.noise_scale
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised, uncond_denoised = pair.call_with_uncond(x, sigmas[i])
            sigma_down, sigma_up = _ancestral_step(sigmas[i], sigmas[i + 1], eta)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigma_down == 0:
                # Euler method (the reference's d * sigma_down term is
                # exactly zero here; kept for the transcription)
                d = _to_d(x, sigmas[i], uncond_denoised)
                x = denoised + d * sigma_down
            else:
                # DPM-Solver++(2S): t = -log(sigma), sigma_fn(t) = exp(-t)
                t = -math.log(sigmas[i])
                t_next = -math.log(sigma_down)
                r = 1.0 / 2.0
                h = t_next - t
                s = t + r * h
                x_2 = (x + (denoised - uncond_denoised)) * (
                    math.exp(-s) / sigmas[i]
                ) - denoised * math.expm1(-h * r)
                denoised_2, uncond_denoised_2 = pair.call_with_uncond(x_2, math.exp(-s))
                x = (x + (denoised - uncond_denoised_2)) * (
                    sigma_down / sigmas[i]
                ) - denoised_2 * math.expm1(-h)
            # Noise addition
            if sigmas[i + 1] > 0:
                coeff = s_noise_eff * sigma_up
                if coeff != 0.0:
                    x = (
                        x
                        + _require_noise(noise, "dpmpp_2s_ancestral_cfg_pp")(
                            sigmas[i], sigmas[i + 1]
                        )
                        * coeff
                    )
        return x

    return solve


def _res_multistep(*, eta: float, s_noise: float, cfg_pp: bool, what: str) -> SolverFn[Any]:
    """Shared res_multistep core (res_multistep @ b78cec87).

    The CFG++ path rides the unconditioned derivative and stores the
    unconditioned history; its second-order branch deliberately shifts
    x by ``denoised - uncond_denoised`` before the exponential update.
    s_noise follows the reference's model_sampling noise_scale probe.

    Deliberate deviation: duplicate consecutive sigmas can make h or
    c2 zero; the reference's nan_to_num only masks b1/b2 NaNs while
    other invalid values cascade. This port raises ValueError naming
    the degenerate schedule instead. At eta 0, sigma_up is identically
    zero, so s_noise is inert and the deterministic wrappers expose no
    churn option."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        pair = _require_uncond(denoiser, what) if cfg_pp else None
        s_noise_eff = s_noise * info.noise_scale
        old_sigma_down: float | None = None
        old_denoised: TensorT | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            if pair is not None:
                denoised, uncond_denoised = pair.call_with_uncond(x, sigmas[i])
            else:
                denoised = denoiser(x, sigmas[i])
                uncond_denoised = denoised
            sigma_down, sigma_up = _ancestral_step(sigmas[i], sigmas[i + 1], eta)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigma_down == 0 or old_denoised is None:
                # Euler method
                if cfg_pp:
                    d = _to_d(x, sigmas[i], uncond_denoised)
                    x = denoised + d * sigma_down
                else:
                    d = _to_d(x, sigmas[i], denoised)
                    dt = sigma_down - sigmas[i]
                    x = x + d * dt
            else:
                # Second-order multistep method (arXiv 2308.02157).
                assert old_sigma_down is not None
                t = -math.log(sigmas[i])
                t_old = -math.log(old_sigma_down)
                t_next = -math.log(sigma_down)
                t_prev = -math.log(sigmas[i - 1])
                h = t_next - t
                if h == 0.0:
                    raise ValueError(
                        f"{what} cannot run a degenerate schedule:"
                        " duplicate consecutive sigmas make h zero"
                    )
                c2 = (t_prev - t_old) / h
                if c2 == 0.0:
                    raise ValueError(
                        f"{what} cannot run a degenerate schedule:"
                        " duplicate consecutive sigmas make c2 zero"
                    )
                phi1 = math.expm1(-h) / (-h)
                phi2 = (phi1 - 1.0) / (-h)
                b1 = phi1 - phi2 / c2
                b2 = phi2 / c2
                if cfg_pp:
                    x = x + (denoised - uncond_denoised)
                    x = x * math.exp(-h) + (uncond_denoised * b1 + old_denoised * b2) * h
                else:
                    x = x * math.exp(-h) + (denoised * b1 + old_denoised * b2) * h
            if sigmas[i + 1] > 0:
                coeff = s_noise_eff * sigma_up
                if coeff != 0.0:
                    x = x + _require_noise(noise, what)(sigmas[i], sigmas[i + 1]) * coeff
            old_denoised = uncond_denoised if cfg_pp else denoised
            old_sigma_down = sigma_down
        return x

    return solve


