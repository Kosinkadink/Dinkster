"""Solver ports: k_diffusion's core sampling algorithms, torch-free.

Every solver here is a line-by-line port of the corresponding
``sample_*`` function in comfy/k_diffusion/sampling.py at the audited
reference commit b78cec87, proven against goldens generated by
executing that very code (tools/gen_sampling_goldens.py, "solvers"
section). What changed is the boundary, not the math:

- sigmas are Python floats, so the reference's zero-dim-tensor
  transcendentals (``sigma.log().neg().exp()``) become ``math.*`` calls;
  tensor arithmetic is only ever elementwise add/sub/mul against the
  ArithTensor protocol, with tensors kept on the LEFT of ``*`` (the
  protocol has no __rmul__).
- model_sampling probing (``model.inner_model.inner_model``,
  ``model_patcher.get_model_object``) becomes SamplerInfo data: the
  RF/CONST isinstance dispatch is ``parameterization is FLOW``, the
  ``noise_scale`` getattr is ``info.noise_scale``.
- noise is injected (NoiseSampler) instead of default-constructed;
  descriptors declare the required NoiseKind. Deliberate deviations,
  each behavior-preserving where the reference is deterministic:
  churn noise in euler/heun/dpm_2 comes through the injected sampler
  (the reference hardcodes torch.randn_like, unseedable); noise calls
  whose coefficient is exactly 0.0 are skipped (the reference draws
  and discards, e.g. euler_ancestral at eta=0).
- ``sigmas[i + 1] == 0`` cases that the reference sails through on IEEE
  infinities (log(0) = -inf, exp(-inf) = 0 in dpmpp_2m) are explicit
  branches with the identical limit value, since math.log(0) raises.

The CFG++ family (euler_cfg_pp, euler_ancestral_cfg_pp,
dpmpp_2s_ancestral_cfg_pp, dpmpp_2m_cfg_pp) consumes the
unconditioned prediction alongside the combined one: the reference
smuggles it out of sampling_function via a post-CFG hook with
disable_cfg1_optimization=True (@ b78cec87); here the denoiser
declares the UncondDenoiser capability (call_with_uncond) and the
solver narrows to it loudly (_require_uncond). Descriptors carry
``needs_uncond`` so callers can check before building.

Solvers NOT ported here are ledgered in ROADMAP.md ("Native
inference"): lcm's s_noise_end/noise_clip_std extras need tensor
clamp/std ops, and the remaining unavailable samplers wait for demand.

Typing note: solver bodies are generic over TensorT (internally
type-checked against ArithTensor), but factories and descriptors are
typed at SolverFn[Any]. A descriptor is really rank-2 polymorphic
("for all tensor types") which Python's type system cannot express -
parameterizing descriptors at ArithTensor would reject every concrete
Denoiser[torch.Tensor] at the call site because Denoiser is invariant.
"""

