def builtin_samplers() -> tuple[SamplerDescriptor[Any], ...]:
    """The sampler catalog, in SAMPLER_NAMES order (@ b78cec87).

    Constructed fresh on every call from field values captured at
    import: distributed receipt admission trusts this catalog, so it
    must never hand back the caller-reachable descriptor constants or
    share any mutable nested object with them. Raises RuntimeError when
    a factory's import-time behavior evidence no longer matches."""
    return tuple(
        SamplerDescriptor(**catalog_descriptor_rebuild(field_values))
        for field_values in _CANONICAL_SAMPLER_FIELDS
    )


def builtin_sampler_registry() -> Registry[SamplerDescriptor[Any]]:
    """A fresh registry preloaded with the ported solver catalog."""
    registry: Registry[SamplerDescriptor[Any]] = Registry()
    for descriptor in builtin_samplers():
        registry.register(descriptor)
    return registry


def select_builtin_sampler(sampler_id: str, **overrides: object) -> BuiltinSamplerSelection:
    """Create an immutable validated selection from the built-in catalog."""
    from dinkster_inference.registries import builtin_registries

    descriptor = builtin_registries().samplers.get(sampler_id)
    if descriptor is None:
        raise ValueError(f"unknown built-in sampler {sampler_id!r}")
    resolved = resolve_options(descriptor.options, overrides)
    return BuiltinSamplerSelection(
        descriptor.id,
        tuple((spec.name, resolved[spec.name]) for spec in descriptor.options),
    )


