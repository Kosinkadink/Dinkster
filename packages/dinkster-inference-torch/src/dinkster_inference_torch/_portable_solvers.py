def seeds_3(
    *, eta: float = 1.0, s_noise: float = 1.0, r_1: float = 1 / 3, r_2: float = 2 / 3
) -> SolverFn[Any]:
    """SEEDS-3 (sample_seeds_3 @ b78cec87)."""
    _check_ancestral_eta(eta)
    if not 0 < r_1 < r_2 <= 1:
        raise ValueError(f"seeds_3 requires 0 < r_1 < r_2 <= 1, got {r_1}, {r_2}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        flow = is_flow_parameterization(info.parameterization)
        s_noise_eff = s_noise * info.noise_scale
        inject_noise = eta > 0 and s_noise_eff > 0
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            ss, st = sigmas[i], sigmas[i + 1]
            d1 = denoiser(x, ss)
            _emit(on_step, info, i, n, ss, x, d1)
            if st == 0:
                x = d1
                continue
            if ss <= 0 or (flow and (ss >= 1 or st >= 1)):
                raise ValueError("seeds_3 degenerate schedule: sigma outside half-logSNR domain")
            ls, lt = _half_log_snr(ss, flow=flow), _half_log_snr(st, flow=flow)
            h = lt - ls
            if h == 0:
                raise ValueError("seeds_3 degenerate schedule: repeated half-logSNR")
            he = h * (eta + 1)
            l1, l2 = ls + r_1 * h, ls + r_2 * h
            s1, s2 = (
                _sigma_from_half_log_snr(l1, flow=flow),
                _sigma_from_half_log_snr(l2, flow=flow),
            )
            a1, a2, at = _alpha(s1, l1), _alpha(s2, l2), _alpha(st, lt)
            x2 = x * (s1 / ss * math.exp(-r_1 * h * eta)) - d1 * (a1 * _phi_1(-r_1 * he))
            sn: TensorT | None = None
            if inject_noise:
                sn = _require_noise(noise, "seeds_3")(ss, s1) * math.sqrt(
                    max(-math.expm1(-2 * r_1 * h * eta), 0.0)
                )
                x2 = x2 + sn * (s1 * s_noise_eff)
            d2 = denoiser(x2, s1)
            a32 = r_2 / r_1 * _phi_2(-r_2 * he, "seeds_3")
            a31 = _phi_1(-r_2 * he) - a32
            x3 = x * (s2 / ss * math.exp(-r_2 * h * eta)) - (d1 * a31 + d2 * a32) * a2
            if inject_noise:
                assert sn is not None
                seg = (r_1 - r_2) * h * eta
                sn = sn * math.exp(seg) + _require_noise(noise, "seeds_3")(s1, s2) * math.sqrt(
                    max(-math.expm1(2 * seg), 0.0)
                )
                x3 = x3 + sn * (s2 * s_noise_eff)
            d3 = denoiser(x3, s2)
            b3 = _phi_2(-he, "seeds_3") / r_2
            b1 = _phi_1(-he) - b3
            x = x * (st / ss * math.exp(-h * eta)) - (d1 * b1 + d3 * b3) * at
            if inject_noise:
                assert sn is not None
                seg = (r_2 - 1) * h * eta
                sn = sn * math.exp(seg) + _require_noise(noise, "seeds_3")(s2, st) * math.sqrt(
                    max(-math.expm1(2 * seg), 0.0)
                )
                x = x + sn * (st * s_noise_eff)
        return x

    return solve


def _sa_solve(matrix: list[list[float]], values: list[float]) -> list[float]:
    """Solve SA-Solver's at-most-4 by 4 Vandermonde system."""
    n = len(values)
    augmented = [row[:] + [value] for row, value in zip(matrix, values, strict=True)]
    for column in range(n):
        pivot = max(range(column, n), key=lambda row: abs(augmented[row][column]))
        if augmented[pivot][column] == 0:
            raise ValueError("sa_solver degenerate coefficients: singular lambda history")
        augmented[column], augmented[pivot] = augmented[pivot], augmented[column]
        divisor = augmented[column][column]
        augmented[column] = [value / divisor for value in augmented[column]]
        for row in range(n):
            if row == column:
                continue
            factor = augmented[row][column]
            augmented[row] = [
                value - factor * pivot_value
                for value, pivot_value in zip(augmented[row], augmented[column], strict=True)
            ]
    return [row[-1] for row in augmented]


def _sa_b_coeffs(
    sigma_t: float,
    lambdas: Sequence[float],
    lambda_s: float,
    lambda_t: float,
    tau: float,
    *,
    simple_order_2: bool,
    corrector: bool,
) -> list[float]:
    order = len(lambdas)
    tau_mul = 1.0 + tau**2
    h = lambda_t - lambda_s
    alpha_t = sigma_t * math.exp(lambda_t)
    if simple_order_2 and order == 2:
        newest = alpha_t * 0.5 * tau_mul * h
        if corrector:
            oldest = alpha_t * (-math.expm1(-h * tau_mul)) - newest
        else:
            denominator = lambdas[-2] - lambda_s
            if denominator == 0:
                raise ValueError("sa_solver degenerate simple-order-2 predictor: repeated lambda")
            oldest = alpha_t * 0.5 * tau_mul * h**2 / denominator
            newest = alpha_t * (-math.expm1(-h * tau_mul)) - oldest
        return [oldest, newest]
    exponential: list[float] = []
    base = math.exp(-tau_mul * h)
    for p in range(order):
        integral = lambda_t**p - lambda_s**p * base
        for j in range(p - 1, -1, -1):
            coefficient = (
                math.factorial(p) / math.factorial(j) * (-1) ** (p - j) / tau_mul ** (p - j)
            )
            integral += coefficient * (lambda_t**j - lambda_s**j * base)
        exponential.append(integral)
    matrix = [[value**power for value in lambdas] for power in range(order)]
    return [alpha_t * value for value in _sa_solve(matrix, exponential)]


def _sa_tau_interval(start: float, end: float, eta: float = 1.0) -> Callable[[float], float]:
    def tau(sigma: float) -> float:
        return eta if start >= sigma >= end else 0.0

    return tau


def sa_solver(
    *,
    s_noise: float = 1.0,
    predictor_order: int = 3,
    corrector_order: int = 4,
    use_pece: bool = False,
    simple_order_2: bool = False,
    tau_func: Callable[[float], float] | None = None,
) -> SolverFn[Any]:
    """Stochastic Adams predictor-corrector (sample_sa_solver @ b78cec87)."""
    if not 1 <= predictor_order <= 6:
        raise ValueError(f"sa_solver predictor_order must be in [1, 6], got {predictor_order}")
    if not 0 <= corrector_order <= 6:
        raise ValueError(f"sa_solver corrector_order must be in [0, 6], got {corrector_order}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if len(sigmas) <= 1:
            return x
        flow = is_flow_parameterization(info.parameterization)
        lambdas: list[float] = []
        for sigma in sigmas:
            if sigma == 0:
                lambdas.append(math.inf)
            elif sigma < 0 or (flow and sigma >= 1):
                raise ValueError("sa_solver degenerate schedule: sigma outside half-logSNR domain")
            else:
                lambdas.append(_half_log_snr(sigma, flow=flow))
        active_tau = tau_func
        if active_tau is None:
            if info.percent_to_sigma is None:
                raise ValueError(
                    "sa_solver requires SamplerInfo.percent_to_sigma for its default tau interval"
                )
            start, end = info.percent_to_sigma(0.2), info.percent_to_sigma(0.8)
            active_tau = _sa_tau_interval(start, end)
        maximum_order = max(predictor_order, corrector_order)
        predicted = x
        predictions: list[TensorT] = []
        h = tau = 0.0
        previous_noise: TensorT | None = None
        lower_to_end = sigmas[-1] == 0
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(predicted, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], predicted, denoised)
            predictions = [*predictions, denoised][-maximum_order:]
            predictor_used = min(predictor_order, len(predictions))
            corrector_used = (
                0
                if i == 0 or (sigmas[i + 1] == 0 and not use_pece)
                else min(corrector_order, len(predictions))
            )
            if lower_to_end:
                predictor_used = min(predictor_used, len(sigmas) - 2 - i)
                corrector_used = min(corrector_used, len(sigmas) - 1 - i)
            if corrector_used == 0:
                x = predicted
            else:
                coeffs = _sa_b_coeffs(
                    sigmas[i],
                    lambdas[i - corrector_used + 1 : i + 1],
                    lambdas[i - 1],
                    lambdas[i],
                    tau,
                    simple_order_2=simple_order_2,
                    corrector=True,
                )
                x = x * (sigmas[i] / sigmas[i - 1] * math.exp(-(tau**2) * h))
                for prediction, coefficient in zip(
                    predictions[-corrector_used:], coeffs, strict=True
                ):
                    x = x + prediction * coefficient
                if tau > 0 and s_noise > 0:
                    assert previous_noise is not None
                    x = x + previous_noise
                if use_pece:
                    denoised = denoiser(x, sigmas[i])
                    predictions[-1] = denoised
            if sigmas[i + 1] == 0:
                predicted = denoised
                continue
            tau = active_tau(sigmas[i + 1])
            coeffs = _sa_b_coeffs(
                sigmas[i + 1],
                lambdas[i - predictor_used + 1 : i + 1],
                lambdas[i],
                lambdas[i + 1],
                tau,
                simple_order_2=simple_order_2,
                corrector=False,
            )
            h = lambdas[i + 1] - lambdas[i]
            predicted = x * (sigmas[i + 1] / sigmas[i] * math.exp(-(tau**2) * h))
            for prediction, coefficient in zip(predictions[-predictor_used:], coeffs, strict=True):
                predicted = predicted + prediction * coefficient
            if tau > 0 and s_noise > 0:
                coefficient = (
                    sigmas[i + 1]
                    * math.sqrt(-math.expm1(-2 * tau**2 * h))
                    * s_noise
                    * info.noise_scale
                )
                previous_noise = (
                    _require_noise(noise, "sa_solver")(sigmas[i], sigmas[i + 1]) * coefficient
                )
                predicted = predicted + previous_noise
        return predicted

    return solve


