# Shared helpers (comfy/k_diffusion/sampling.py @ b78cec87)


def _adaptive_ops(value: TensorT) -> AdaptiveTensor[TensorT]:
    if not isinstance(value, AdaptiveTensor):
        raise TypeError("dpm_adaptive requires adaptive tensor reduction operations")
    return cast(AdaptiveTensor[TensorT], value)


def _division_ops(value: TensorT, what: str) -> DivTensor[TensorT]:
    if not isinstance(value, DivTensor):
        raise TypeError(f"{what} requires tensor division")
    return cast(DivTensor[TensorT], value)


def _to_d(x: TensorT, sigma: float, denoised: TensorT) -> TensorT:
    """Karras ODE derivative (to_d @ b78cec87): (x - denoised) / sigma,
    as multiplication because sigma is a plain float here."""
    return (x - denoised) * (1.0 / sigma)


def _ancestral_step(sigma_from: float, sigma_to: float, eta: float) -> tuple[float, float]:
    """(sigma_down, sigma_up) for one ancestral step (get_ancestral_step
    @ b78cec87), pure float math. sqrt args are clamped at 0.0 against
    float error - both are mathematically nonnegative for
    0 < sigma_to <= sigma_from and eta <= 1."""
    if not eta:
        return sigma_to, 0.0
    sigma_up = min(
        sigma_to,
        eta * math.sqrt(max(sigma_to**2 * (sigma_from**2 - sigma_to**2) / sigma_from**2, 0.0)),
    )
    sigma_down = math.sqrt(max(sigma_to**2 - sigma_up**2, 0.0))
    return sigma_down, sigma_up


def _half_log_snr(sigma: float, *, flow: bool) -> float:
    """sigma -> half-logSNR log(alpha/sigma) (sigma_to_half_log_snr
    @ b78cec87): logit(sigma).neg() for flow/CONST models, log(sigma).neg()
    otherwise."""
    if flow:
        return math.log((1.0 - sigma) / sigma)
    return -math.log(sigma)


def _sigma_from_half_log_snr(lam: float, *, flow: bool) -> float:
    """half-logSNR -> sigma (half_log_snr_to_sigma @ b78cec87)."""
    if flow:
        return 1.0 / (1.0 + math.exp(lam))
    return math.exp(-lam)


def _alpha(sigma: float, lam: float) -> float:
    """alpha_t = sigma_t * exp(lambda_t) - exactly the reference's
    inline ``sigmas[i] * lambda_s.exp()`` (@ b78cec87); 1.0 for eps-like
    models where lambda = -log(sigma)."""
    return sigma * math.exp(lam)


def _require_uncond(denoiser: Denoiser[TensorT], what: str) -> UncondDenoiser[TensorT]:
    """Narrow a Denoiser to the CFG++ capability or refuse loudly: the
    reference expresses this requirement as a post-CFG hook the solver
    installs blind (@ b78cec87); here it is a checked interface."""
    if not isinstance(denoiser, UncondDenoiser):
        raise ValueError(
            f"{what} is a CFG++ solver: it needs the unconditioned"
            " prediction each step, so the denoiser must provide"
            " call_with_uncond (the UncondDenoiser capability);"
            f" {type(denoiser).__name__} does not"
        )
    return denoiser


def _require_noise(noise: NoiseSampler[TensorT] | None, what: str) -> NoiseSampler[TensorT]:
    if noise is None:
        raise ValueError(
            f"{what} requires a noise sampler; construct one matching the "
            "descriptor's NoiseKind and pass it as noise="
        )
    return noise


def _emit(
    on_step: StepCallback | None,
    info: SamplerInfo,
    i: int,
    total: int,
    sigma: float,
    current: TensorT,
    denoised: TensorT | None,
) -> None:
    if info.on_state is not None:
        info.on_state(
            SolverStateEvent[object](
                step=i,
                total=total,
                sigma=sigma,
                phase="pre_update",
                current=current,
                denoised=denoised,
            )
        )
    if on_step is not None:
        on_step(StepEvent(step=i, total=total, sigma=sigma))


def _begin(on_step_begin: Callable[[int], None] | None, index: int) -> None:
    if on_step_begin is not None:
        on_step_begin(index)


def _churn_gamma(sigma: float, n: int, *, s_churn: float, s_tmin: float, s_tmax: float) -> float:
    """Per-step churn gamma (sample_euler/heun/dpm_2 preamble @ b78cec87)."""
    if s_churn > 0 and s_tmin <= sigma <= s_tmax:
        return min(s_churn / n, math.sqrt(2.0) - 1.0)
    return 0.0


