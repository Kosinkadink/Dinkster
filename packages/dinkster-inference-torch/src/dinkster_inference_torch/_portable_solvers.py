def _make_ar_video(opts: Mapping[str, OptionValue]) -> SolverFn[Any]:
    num_frame_per_block = _i(opts, "num_frame_per_block")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
    ) -> TensorT:
        del noise
        if len(sigmas) <= 1:
            return x
        if not isinstance(denoiser, AutoregressiveDenoiser):
            raise TypeError("ar_video requires an autoregressive denoiser")
        context = sampling_execution_context(sigmas, info.seed, on_step)
        context.cancellation.check()
        result = cast("AutoregressiveDenoiser[TensorT]", denoiser).sample_autoregressive(
            x,
            sigmas,
            info,
            num_frame_per_block=num_frame_per_block,
            on_step=context.progress.report,
        )
        context.cancellation.check()
        return result

    return solve


