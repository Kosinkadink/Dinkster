def _solve_small(matrix: list[list[float]], rhs: list[float], name: str) -> list[float]:
    """Pivoted float solve for UniPC's at-most 3x3 Vandermonde systems."""
    n = len(rhs)
    a = [row[:] + [value] for row, value in zip(matrix, rhs, strict=True)]
    for col in range(n):
        pivot = max(range(col, n), key=lambda row: abs(a[row][col]))
        if abs(a[pivot][col]) <= 1e-14:
            raise ValueError(f"{name} degenerate linear system")
        a[col], a[pivot] = a[pivot], a[col]
        for row in range(col + 1, n):
            factor = a[row][col] / a[col][col]
            for j in range(col, n + 1):
                a[row][j] -= factor * a[col][j]
    out = [0.0] * n
    for row in range(n - 1, -1, -1):
        out[row] = (a[row][n] - sum(a[row][j] * out[j] for j in range(row + 1, n))) / a[row][row]
    return out


def _uni_pc(variant: str) -> SolverFn[Any]:
    name = "uni_pc" if variant == "bh1" else "uni_pc_bh2"

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        del noise
        if len(sigmas) <= 1:
            return x
        x_ops = _division_ops(x, name)
        ts = [
            0.001 if i == len(sigmas) - 1 and sigma == 0.0 else float(sigma)
            for i, sigma in enumerate(sigmas)
        ]
        if any(not math.isfinite(t) or t <= 0.0 for t in ts):
            raise ValueError(f"{name} degenerate schedule: sigmas must be finite and positive")
        order = min(3, len(ts) - 2)
        x = x_ops / math.sqrt(1.0 + ts[0] * ts[0])

        def model(value: TensorT, t: float) -> TensorT:
            # SigmaConvert + predict_eps_sigma + data_prediction_fn collapse
            # exactly to this denoised prediction in the original sigma space.
            return denoiser(value * math.sqrt(1.0 + t * t), t)

        if on_step_begin is not None:
            on_step_begin(0)
        models: list[TensorT] = [model(x, ts[0])]
        times: list[float] = [ts[0]]
        callback_index = 0

        def emit_before_update() -> None:
            nonlocal callback_index
            source_t = times[-1]
            source_model = models[-1]
            if info.on_state is not None and callback_index > 0:
                source_model = model(x, source_t)
            scale = math.sqrt(1.0 + source_t * source_t)
            _emit(
                on_step,
                info,
                callback_index,
                steps,
                source_t,
                x * scale,
                source_model,
            )
            callback_index += 1

        def update(
            value: TensorT, t: float, step_order: int, correct: bool
        ) -> tuple[TensorT, TensorT | None]:
            t0 = times[-1]
            h = -math.log(t) + math.log(t0)
            if not math.isfinite(h) or abs(h) <= 1e-14:
                raise ValueError(f"{name} degenerate schedule: repeated or invalid sigmas")
            m0 = models[-1]
            rks: list[float] = []
            diffs: list[TensorT] = []
            for i in range(1, step_order):
                rk = (-math.log(times[-i - 1]) + math.log(t0)) / h
                if not math.isfinite(rk) or abs(rk) <= 1e-14:
                    raise ValueError(f"{name} degenerate schedule: repeated or invalid history")
                rks.append(rk)
                diffs.append(_division_ops(models[-i - 1] - m0, name) / rk)
            rks.append(1.0)
            hh = -h
            phi1 = math.expm1(hh)
            phi = phi1 / hh - 1.0
            bh = hh if variant == "bh1" else phi1
            if abs(bh) <= 1e-14:
                raise ValueError(f"{name} degenerate B(h)")
            rhs: list[float] = []
            factorial = 1
            for i in range(1, step_order + 1):
                rhs.append(phi * factorial / bh)
                factorial *= i + 1
                phi = phi / hh - 1.0 / factorial
            matrix = [[rk**row for rk in rks] for row in range(step_order)]
            alpha = 1.0 / math.sqrt(1.0 + t * t)
            std_ratio = (t / math.sqrt(1.0 + t * t)) / (t0 / math.sqrt(1.0 + t0 * t0))
            base = value * std_ratio - m0 * (alpha * phi1)
            candidate = base
            if diffs:
                rho_p = (
                    [0.5]
                    if step_order == 2
                    else _solve_small([row[:-1] for row in matrix[:-1]], rhs[:-1], name)
                )
                residual = diffs[0] * rho_p[0]
                for diff, rho in zip(diffs[1:], rho_p[1:], strict=True):
                    residual = residual + diff * rho
                candidate = base - residual * (alpha * bh)
            if not correct:
                return candidate, None
            rho_c = [0.5] if step_order == 1 else _solve_small(matrix, rhs, name)
            model_t = model(candidate, t)
            residual = (model_t - m0) * rho_c[-1]
            for diff, rho in zip(diffs, rho_c[:-1], strict=True):
                residual = residual + diff * rho
            return base - residual * (alpha * bh), model_t

        steps = len(ts) - 1
        for index in range(steps):
            if index > 0 and on_step_begin is not None:
                on_step_begin(index)
            if index == 0:
                if steps == 1:
                    emit_before_update()
            elif index < order:
                emit_before_update()
                x, model_x = update(x, ts[index], index, True)
                models.append(model_x if model_x is not None else model(x, ts[index]))
                times.append(ts[index])
            else:
                last = index == steps - 1
                stop = index + 2 if last else index + 1
                for step in range(index, stop):
                    emit_before_update()
                    step_order = min(order, steps + 1 - step)
                    x, model_x = update(x, ts[step], step_order, step < steps)
                    models = models[1:] + [model_x if model_x is not None else models[-1]]
                    times = times[1:] + [ts[step]]
        if callback_index != steps:
            raise RuntimeError("UniPC callback count does not match its schedule")
        return x * math.sqrt(1.0 + ts[-1] * ts[-1])

    return solve


