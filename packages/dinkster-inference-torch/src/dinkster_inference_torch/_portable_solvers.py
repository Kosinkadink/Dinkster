_SNR_OFFSET_HINT = (
    "flow-model SDE solvers need sigmas[0] < 1 for a finite logSNR; "
    "apply schedules.offset_first_sigma_for_snr to the schedule first "
    "(the reference clamps inside the solver via model_sampling probing "
    "@ b78cec87; here schedule preparation owns it)"
)


def dpmpp_sde(*, eta: float = 1.0, s_noise: float = 1.0, r: float = 0.5) -> SolverFn[Any]:
    """DPM-Solver++ stochastic (sample_dpmpp_sde @ b78cec87)."""
    if r <= 0:
        raise ValueError(f"r must be > 0, got {r}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if len(sigmas) <= 1:
            return x
        flow = is_flow_parameterization(info.parameterization)
        if flow and sigmas[0] >= 1.0:
            raise ValueError(_SNR_OFFSET_HINT)
        s_noise_eff = s_noise * info.noise_scale
        stochastic = eta > 0 and s_noise_eff > 0
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                lam_s = _half_log_snr(sigmas[i], flow=flow)
                lam_t = _half_log_snr(sigmas[i + 1], flow=flow)
                h = lam_t - lam_s
                lam_s_1 = lam_s + r * h
                fac = 1.0 / (2.0 * r)
                sigma_s_1 = _sigma_from_half_log_snr(lam_s_1, flow=flow)
                alpha_s = _alpha(sigmas[i], lam_s)
                alpha_s_1 = _alpha(sigma_s_1, lam_s_1)
                alpha_t = _alpha(sigmas[i + 1], lam_t)

                # Step 1 (midpoint at r)
                sd, su = _ancestral_step(math.exp(-lam_s), math.exp(-lam_s_1), eta)
                h_ = -math.log(sd) - lam_s
                x_2 = x * ((alpha_s_1 / alpha_s) * math.exp(-h_)) - denoised * (
                    alpha_s_1 * math.expm1(-h_)
                )
                if stochastic:
                    x_2 = x_2 + _require_noise(noise, "dpmpp_sde")(sigmas[i], sigma_s_1) * (
                        alpha_s_1 * s_noise_eff * su
                    )
                denoised_2 = denoiser(x_2, sigma_s_1)

                # Step 2
                sd, su = _ancestral_step(math.exp(-lam_s), math.exp(-lam_t), eta)
                h_ = -math.log(sd) - lam_s
                denoised_d = denoised * (1.0 - fac) + denoised_2 * fac
                x = x * ((alpha_t / alpha_s) * math.exp(-h_)) - denoised_d * (
                    alpha_t * math.expm1(-h_)
                )
                if stochastic:
                    x = x + _require_noise(noise, "dpmpp_sde")(sigmas[i], sigmas[i + 1]) * (
                        alpha_t * s_noise_eff * su
                    )
        return x

    return solve


def dpmpp_2m() -> SolverFn[Any]:
    """DPM-Solver++(2M) (sample_dpmpp_2m @ b78cec87) - deterministic,
    no options."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        old_denoised: TensorT | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                # reference reaches this via t_next = inf: ratio 0, -expm1(-inf) = 1
                x = denoised
            else:
                h = math.log(sigmas[i]) - math.log(sigmas[i + 1])
                ratio = sigmas[i + 1] / sigmas[i]
                if old_denoised is None:
                    x = x * ratio - denoised * math.expm1(-h)
                else:
                    h_last = math.log(sigmas[i - 1]) - math.log(sigmas[i])
                    rr = h_last / h
                    denoised_d = denoised * (1.0 + 1.0 / (2.0 * rr)) - old_denoised * (
                        1.0 / (2.0 * rr)
                    )
                    x = x * ratio - denoised_d * math.expm1(-h)
            old_denoised = denoised
        return x

    return solve


def dpmpp_2m_cfg_pp() -> SolverFn[Any]:
    """DPM-Solver++(2M), CFG++ (sample_dpmpp_2m_cfg_pp @ b78cec87) -
    deterministic, no options. The multistep history carries the
    UNCONDITIONED predictions; the combined one anchors each update."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        pair = _require_uncond(denoiser, "dpmpp_2m_cfg_pp")
        old_uncond_denoised: TensorT | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised, uncond_denoised = pair.call_with_uncond(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                # reference reaches this via t_next = inf: exp(-h) = 0
                # kills both the mix and the x carry-term
                x = denoised
            else:
                h = math.log(sigmas[i]) - math.log(sigmas[i + 1])
                eh = math.exp(-h)
                if old_uncond_denoised is None:
                    denoised_mix = uncond_denoised * (-eh)
                else:
                    h_last = math.log(sigmas[i - 1]) - math.log(sigmas[i])
                    rr = h_last / h
                    denoised_mix = uncond_denoised * (-eh) - (denoised - old_uncond_denoised) * (
                        math.expm1(-h) * (1.0 / (2.0 * rr))
                    )
                x = denoised + denoised_mix + x * eh
            old_uncond_denoised = uncond_denoised
        return x

    return solve


def dpmpp_2m_sde(
    *, eta: float = 1.0, s_noise: float = 1.0, solver_type: str = "midpoint"
) -> SolverFn[Any]:
    """DPM-Solver++(2M) SDE (sample_dpmpp_2m_sde @ b78cec87)."""
    if solver_type not in ("midpoint", "heun"):
        raise ValueError(f"solver_type must be 'midpoint' or 'heun', got {solver_type!r}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if len(sigmas) <= 1:
            return x
        flow = is_flow_parameterization(info.parameterization)
        if flow and sigmas[0] >= 1.0:
            raise ValueError(_SNR_OFFSET_HINT)
        s_noise_eff = s_noise * info.noise_scale
        old_denoised: TensorT | None = None
        h: float | None = None
        h_last: float | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                lam_s = _half_log_snr(sigmas[i], flow=flow)
                lam_t = _half_log_snr(sigmas[i + 1], flow=flow)
                h = lam_t - lam_s
                h_eta = h * (eta + 1.0)
                alpha_t = _alpha(sigmas[i + 1], lam_t)
                x = x * ((sigmas[i + 1] / sigmas[i]) * math.exp(-h * eta)) + denoised * (
                    alpha_t * -math.expm1(-h_eta)
                )
                if old_denoised is not None:
                    assert h_last is not None
                    rr = h_last / h
                    if solver_type == "heun":
                        coeff = alpha_t * (-math.expm1(-h_eta) / -h_eta + 1.0) * (1.0 / rr)
                    else:
                        coeff = 0.5 * alpha_t * -math.expm1(-h_eta) * (1.0 / rr)
                    x = x + (denoised - old_denoised) * coeff
                if eta > 0 and s_noise_eff > 0:
                    x = x + _require_noise(noise, "dpmpp_2m_sde")(sigmas[i], sigmas[i + 1]) * (
                        sigmas[i + 1] * math.sqrt(-math.expm1(-2.0 * h * eta)) * s_noise_eff
                    )
            old_denoised = denoised
            h_last = h
        return x

    return solve


def dpmpp_3m_sde(*, eta: float = 1.0, s_noise: float = 1.0) -> SolverFn[Any]:
    """DPM-Solver++(3M) SDE (sample_dpmpp_3m_sde @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        if len(sigmas) <= 1:
            return x
        flow = is_flow_parameterization(info.parameterization)
        if flow and sigmas[0] >= 1.0:
            raise ValueError(_SNR_OFFSET_HINT)
        s_noise_eff = s_noise * info.noise_scale
        denoised_1: TensorT | None = None
        denoised_2: TensorT | None = None
        h: float | None = None
        h_1: float | None = None
        h_2: float | None = None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                lam_s = _half_log_snr(sigmas[i], flow=flow)
                lam_t = _half_log_snr(sigmas[i + 1], flow=flow)
                h = lam_t - lam_s
                h_eta = h * (eta + 1.0)
                alpha_t = _alpha(sigmas[i + 1], lam_t)
                x = x * ((sigmas[i + 1] / sigmas[i]) * math.exp(-h * eta)) + denoised * (
                    alpha_t * -math.expm1(-h_eta)
                )
                if h_2 is not None:
                    assert h_1 is not None and denoised_1 is not None
                    assert denoised_2 is not None
                    r0 = h_1 / h
                    r1 = h_2 / h
                    d1_0 = (denoised - denoised_1) * (1.0 / r0)
                    d1_1 = (denoised_1 - denoised_2) * (1.0 / r1)
                    d1 = d1_0 + (d1_0 - d1_1) * (r0 / (r0 + r1))
                    d2 = (d1_0 - d1_1) * (1.0 / (r0 + r1))
                    phi_2 = math.expm1(-h_eta) / h_eta + 1.0
                    phi_3 = phi_2 / h_eta - 0.5
                    x = x + d1 * (alpha_t * phi_2) - d2 * (alpha_t * phi_3)
                elif h_1 is not None:
                    assert denoised_1 is not None
                    rr = h_1 / h
                    d = (denoised - denoised_1) * (1.0 / rr)
                    phi_2 = math.expm1(-h_eta) / h_eta + 1.0
                    x = x + d * (alpha_t * phi_2)
                if eta > 0 and s_noise_eff > 0:
                    x = x + _require_noise(noise, "dpmpp_3m_sde")(sigmas[i], sigmas[i + 1]) * (
                        sigmas[i + 1] * math.sqrt(-math.expm1(-2.0 * h * eta)) * s_noise_eff
                    )
            denoised_1, denoised_2 = denoised, denoised_1
            h_1, h_2 = h, h_1
        return x

    return solve


def ddpm() -> SolverFn[Any]:
    """DDPM over the discrete-eps sigma parameterization (sample_ddpm /
    generic_step_sampler / DDPMSampler_step @ b78cec87). Assumes the
    variance-exploding discrete sigma convention (alpha_cumprod =
    1 / (sigma^2 + 1)); not meaningful on flow sigmas."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            s = sigmas[i]
            s_prev = sigmas[i + 1]
            x_in = x * (1.0 / math.sqrt(1.0 + s * s))
            noise_est = (x - denoised) * (1.0 / s)
            alpha_cumprod = 1.0 / (s * s + 1.0)
            alpha_cumprod_prev = 1.0 / (s_prev * s_prev + 1.0)
            alpha = alpha_cumprod / alpha_cumprod_prev
            mu = (x_in - noise_est * ((1.0 - alpha) / math.sqrt(1.0 - alpha_cumprod))) * math.sqrt(
                1.0 / alpha
            )
            if s_prev > 0:
                mu = mu + _require_noise(noise, "ddpm")(s, s_prev) * math.sqrt(
                    (1.0 - alpha) * (1.0 - alpha_cumprod_prev) / (1.0 - alpha_cumprod)
                )
            x = mu
            if s_prev != 0:
                x = x * math.sqrt(1.0 + s_prev * s_prev)
        return x

    return solve


def lcm(
    *, s_noise: float = 1.0, s_noise_end: float | None = None, noise_clip_std: float = 0.0
) -> SolverFn[Any]:
    """LCM (sample_lcm @ b78cec87): denoise fully, renoise to the next
    sigma via the parameterization's noise_scaling. The reference's
    s_noise_end interpolation and noise_clip_std clamp included."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        s_end = s_noise if s_noise_end is None else s_noise_end
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            x = denoised
            if sigmas[i + 1] > 0:
                fresh = _require_noise(noise, "lcm")(sigmas[i], sigmas[i + 1])
                if noise_clip_std > 0:
                    if not isinstance(fresh, LCMClipTensor):
                        raise TypeError(
                            "lcm noise clipping requires tensor clamp and std operations"
                        )
                    fresh_ops = cast(LCMClipTensor[TensorT], fresh)
                    clip_val = noise_clip_std * float(fresh_ops.std())
                    fresh = fresh_ops.clamp(-clip_val, clip_val)
                t = i / (n - 1) if n > 1 else 0.0
                s_noise_i = s_noise + (s_end - s_noise) * t
                if s_noise_i != 1.0:
                    fresh = fresh * s_noise_i
                x = noise_scaling(
                    info.parameterization,
                    sigmas[i + 1],
                    fresh,
                    x,
                    noise_scale=info.noise_scale,
                )
        return x

    return solve


def heunpp2(
    *,
    s_churn: float = 0.0,
    s_tmin: float = 0.0,
    s_tmax: float = math.inf,
    s_noise: float = 1.0,
) -> SolverFn[Any]:
    """Heun++ (sample_heunpp2 @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        n = len(sigmas) - 1
        if n <= 0:
            return x
        s_end = sigmas[-1]
        for i in range(n):
            _begin(on_step_begin, i)
            gamma = min(s_churn / n, math.sqrt(2.0) - 1.0) if s_tmin <= sigmas[i] <= s_tmax else 0.0
            sigma_hat = sigmas[i] * (gamma + 1.0)
            if gamma > 0:
                x = x + _require_noise(noise, "heunpp2")(sigmas[i], sigma_hat) * (
                    s_noise * math.sqrt(sigma_hat**2 - sigmas[i] ** 2)
                )
            denoised = denoiser(x, sigma_hat)
            d = _to_d(x, sigma_hat, denoised)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            dt = sigmas[i + 1] - sigma_hat
            if sigmas[i + 1] == s_end:
                x = x + d * dt
            elif sigmas[i + 2] == s_end:
                x_2 = x + d * dt
                d_2 = _to_d(x_2, sigmas[i + 1], denoiser(x_2, sigmas[i + 1]))
                w = 2 * sigmas[0]
                if w == 0:
                    raise ValueError("heunpp2 degenerate schedule: first sigma is zero")
                w2 = sigmas[i + 1] / w
                x = x + (d * (1 - w2) + d_2 * w2) * dt
            else:
                x_2 = x + d * dt
                d_2 = _to_d(x_2, sigmas[i + 1], denoiser(x_2, sigmas[i + 1]))
                dt_2 = sigmas[i + 2] - sigmas[i + 1]
                x_3 = x_2 + d_2 * dt_2
                d_3 = _to_d(x_3, sigmas[i + 2], denoiser(x_3, sigmas[i + 2]))
                w = 3 * sigmas[0]
                if w == 0:
                    raise ValueError("heunpp2 degenerate schedule: first sigma is zero")
                w2, w3 = sigmas[i + 1] / w, sigmas[i + 2] / w
                x = x + (d * (1 - w2 - w3) + d_2 * w2 + d_3 * w3) * dt
        return x

    return solve


def _lms_coeff(order: int, sigmas: Sequence[float], i: int, j: int) -> float:
    # Exact integral of the Lagrange basis polynomial used by
    # linear_multistep_coeff (the reference evaluates this with scipy.quad).
    poly = [1.0]
    for k in range(order):
        if j == k:
            continue
        den = sigmas[i - j] - sigmas[i - k]
        if den == 0:
            raise ValueError("lms degenerate schedule: repeated sigma in history")
        root = sigmas[i - k]
        out = [0.0] * (len(poly) + 1)
        for p, value in enumerate(poly):
            out[p] += -root * value / den
            out[p + 1] += value / den
        poly = out
    a, b = sigmas[i], sigmas[i + 1]
    return sum(c * (b ** (p + 1) - a ** (p + 1)) / (p + 1) for p, c in enumerate(poly))


def lms(*, order: int = 4) -> SolverFn[Any]:
    """Linear multistep sampler (sample_lms @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        ds: list[TensorT] = []
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            d = _to_d(x, sigmas[i], denoised)
            ds.append(d)
            if len(ds) > order:
                ds.pop(0)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                cur_order = min(i + 1, order)
                for j, old_d in enumerate(reversed(ds)):
                    x = x + old_d * _lms_coeff(cur_order, sigmas, i, j)
        return x

    return solve


def ipndm(*, max_order: int = 4, variable: bool = False) -> SolverFn[Any]:
    """iPNDM fixed/variable-step Adams sampler (@ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        history: list[TensorT] = []
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            cur, nxt = sigmas[i], sigmas[i + 1]
            denoised = denoiser(x, cur)
            _emit(on_step, info, i, n, cur, x, denoised)
            d = _to_d(x, cur, denoised)
            order = min(max_order, i + 1)
            if nxt == 0:
                x = denoised
            elif not variable:
                coeffs = (
                    (1,),
                    (3 / 2, -1 / 2),
                    (23 / 12, -16 / 12, 5 / 12),
                    (55 / 24, -59 / 24, 37 / 24, -9 / 24),
                )[order - 1]
                terms = [d, *reversed(history)]
                step = terms[0] * coeffs[0]
                for c, term in zip(coeffs[1:], terms[1:], strict=True):
                    step = step + term * c
                x = x + step * (nxt - cur)
            else:
                terms = [d, *reversed(history)]
                h = nxt - cur
                h1 = cur - sigmas[i - 1] if order >= 2 else 1.0
                if order >= 2 and h1 == 0:
                    raise ValueError("ipndm_v degenerate schedule: repeated sigma")
                if order == 1:
                    coeffs = (1.0,)
                elif order == 2:
                    coeffs = ((2 + h / h1) / 2, -(h / h1) / 2)
                else:
                    h2 = sigmas[i - 1] - sigmas[i - 2]
                    if h2 == 0 or h1 + h2 == 0 or h + h1 == 0:
                        raise ValueError("ipndm_v degenerate schedule: repeated sigma")
                    temp1 = (1 - h / (3 * (h + h1)) * (h * (h + h1)) / (h1 * (h1 + h2))) / 2
                    if order == 3:
                        coeffs = (
                            (2 + h / h1) / 2 + temp1,
                            -(h / h1) / 2 - (1 + h1 / h2) * temp1,
                            temp1 * h1 / h2,
                        )
                    else:
                        h3 = sigmas[i - 2] - sigmas[i - 3]
                        if h3 == 0 or h2 + h3 == 0 or h1 + h2 + h3 == 0:
                            raise ValueError("ipndm_v degenerate schedule: repeated sigma")
                        temp2 = (
                            (
                                (1 - h / (3 * (h + h1))) / 2
                                + (1 - h / (2 * (h + h1))) * h / (6 * (h + h1 + h2))
                            )
                            * (h * (h + h1) * (h + h1 + h2))
                            / (h1 * (h1 + h2) * (h1 + h2 + h3))
                        )
                        ratio = h1 * (h1 + h2) / (h2 * (h2 + h3))
                        coeffs = (
                            (2 + h / h1) / 2 + temp1 + temp2,
                            -(h / h1) / 2 - (1 + h1 / h2) * temp1 - (1 + h1 / h2 + ratio) * temp2,
                            temp1 * h1 / h2 + (h1 / h2 + ratio * (1 + h2 / h3)) * temp2,
                            -temp2 * ratio * h1 / h2,
                        )
                step = terms[0] * coeffs[0]
                for coefficient, term in zip(coeffs[1:], terms[1:], strict=True):
                    step = step + term * coefficient
                x = x + step * h
            if len(history) == max_order - 1:
                history.pop(0)
            history.append(d)
        return x

    return solve


def ipndm_v(*, max_order: int = 4) -> SolverFn[Any]:
    return ipndm(max_order=max_order, variable=True)


def _deis_coefficients(
    sigmas: Sequence[float], max_order: int, *, points: int = 10_000
) -> list[list[float]]:
    """Torch-free get_deis_coeff_list ``tab`` mode (@ b78cec87)."""
    # edm2t constructs sigma_min/max tensors without a dtype, so these
    # constants preserve the reference's float32-origin values exactly.
    beta_0 = float.fromhex("-0x1.350e4d7e74000p-8")
    beta_1 = float.fromhex("0x1.1887b863e6da7p+4")
    beta_d = beta_1 - beta_0
    times = [
        (math.sqrt(beta_0**2 + 2 * beta_d * math.log(sigma**2 + 1)) - beta_0) / beta_d
        for sigma in sigmas
    ]
    coefficients: list[list[float]] = []
    for i, (cur, nxt) in enumerate(zip(times[:-1], times[1:], strict=True)):
        order = min(i + 1, max_order)
        # sample_deis forces the terminal step to Euler, so the reference's
        # singular, unused terminal tabulation need not be materialized.
        if order == 1 or sigmas[i + 1] <= 0:
            if i > 0 and len(set(times[max(0, i - order + 1) : i + 1])) < order:
                raise ValueError("deis degenerate schedule: repeated transformed time in history")
            coefficients.append([])
            continue
        previous = [times[i - k] for k in range(order)]
        if len(set(previous)) != len(previous):
            raise ValueError("deis degenerate schedule: repeated transformed time in history")
        step = (nxt - cur) / (points - 1)
        dtau = (nxt - cur) / points  # Deliberately matches the reference's tab quadrature.
        sums = [0.0] * order
        for n in range(points):
            tau = cur + step * n
            alpha = math.exp(-0.5 * tau**2 * (beta_1 - beta_0) - tau * beta_0)
            radicand = alpha * (1 - alpha)
            if radicand <= 0:
                raise ValueError("deis degenerate schedule: tab integrand outside VP domain")
            integrand = 0.5 * (tau * (beta_1 - beta_0) + beta_0) / math.sqrt(radicand)
            for j in range(order):
                poly = 1.0
                for k in range(order):
                    if k != j:
                        poly *= (tau - previous[k]) / (previous[j] - previous[k])
                sums[j] += integrand * poly
        coefficients.append([value * dtau for value in sums])
    return coefficients


def deis(*, max_order: int = 3, deis_mode: str = "tab") -> SolverFn[Any]:
    """DEIS tabulated multistep sampler (sample_deis @ b78cec87)."""
    if not 1 <= max_order <= 4:
        raise ValueError(f"deis max_order must be in [1, 4], got {max_order}")
    if deis_mode != "tab":
        raise ValueError(f"deis_mode must be 'tab', got {deis_mode!r}")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        coeffs = _deis_coefficients(sigmas, max_order)
        history: list[TensorT] = []
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            cur, nxt = sigmas[i], sigmas[i + 1]
            if cur == 0:
                raise ValueError("deis degenerate schedule: current sigma is zero")
            denoised = denoiser(x, cur)
            _emit(on_step, info, i, n, cur, x, denoised)
            derivative = _to_d(x, cur, denoised)
            order = 1 if nxt <= 0 else min(max_order, i + 1)
            if order == 1:
                x = x + derivative * (nxt - cur)
            else:
                terms = [derivative, *reversed(history)]
                for coefficient, term in zip(coeffs[i], terms, strict=True):
                    x = x + term * coefficient
            if len(history) == max_order - 1:
                history.pop(0)
            history.append(derivative)
        return x

    return solve


def gradient_estimation(*, ge_gamma: float = 2.0, cfg_pp: bool = False) -> SolverFn[Any]:
    """Gradient-estimation sampler (sample_gradient_estimation @ b78cec87)."""

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        old_d: TensorT | None = None
        model = _require_uncond(denoiser, "gradient_estimation_cfg_pp") if cfg_pp else None
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            if model is None:
                denoised = denoiser(x, sigmas[i])
                basis = denoised
            else:
                denoised, basis = model.call_with_uncond(x, sigmas[i])
            d = _to_d(x, sigmas[i], basis)
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            dt = sigmas[i + 1] - sigmas[i]
            if sigmas[i + 1] == 0:
                x = denoised
            else:
                x = denoised + d * sigmas[i + 1] if cfg_pp else x + d * dt
                if i >= 1:
                    assert old_d is not None
                    x = x + (d - old_d) * ((ge_gamma - 1) * dt)
            old_d = d
        return x

    return solve


def gradient_estimation_cfg_pp(*, ge_gamma: float = 2.0) -> SolverFn[Any]:
    return gradient_estimation(ge_gamma=ge_gamma, cfg_pp=True)


def _phi_1(h: float) -> float:
    return math.expm1(h)


def _phi_2(h: float, what: str) -> float:
    if h == 0:
        raise ValueError(f"{what} degenerate schedule: repeated half-logSNR")
    return (math.expm1(h) - h) / h


def er_sde(
    *,
    s_noise: float = 1.0,
    noise_scaler: Callable[[float], float] | None = None,
    max_stage: int = 3,
    solver_type: str = "ER-SDE",
    eta: float = 1.0,
) -> SolverFn[Any]:
    """Extended reverse-time SDE solver with SamplerER_SDE modes @ 76135e55."""
    if not 1 <= max_stage <= 3:
        raise ValueError(f"er_sde max_stage must be in [1, 3], got {max_stage}")
    if solver_type not in {"ER-SDE", "Reverse-time SDE", "ODE"}:
        raise ValueError("er_sde solver_type must be 'ER-SDE', 'Reverse-time SDE', or 'ODE'")
    if not math.isfinite(eta) or not 0 <= eta <= 100:
        raise ValueError(f"er_sde eta must be in [0, 100], got {eta}")
    if noise_scaler is not None and (solver_type != "ER-SDE" or eta != 1.0):
        raise ValueError(
            "er_sde noise_scaler cannot be combined with a non-default solver_type or eta"
        )
    if solver_type == "ODE" or eta == 0:
        solver_type = "ODE"
        s_noise = 0.0

    def default_er_sde_scale(value: float) -> float:
        return value * (math.exp(value**0.3) + 10.0)

    def eta_er_sde_scale(value: float) -> float:
        return value * (math.exp(value**0.3) + 10.0) ** eta

    def reverse_time_scale(value: float) -> float:
        return value ** (eta + 1.0)

    def ode_scale(value: float) -> float:
        return value

    if noise_scaler is not None:
        scale = noise_scaler
    elif solver_type == "ER-SDE":
        scale = default_er_sde_scale if eta == 1.0 else eta_er_sde_scale
    elif solver_type == "Reverse-time SDE":
        scale = reverse_time_scale
    else:
        scale = ode_scale

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        flow = is_flow_parameterization(info.parameterization)
        if flow and sigmas and sigmas[0] >= 1.0:
            raise ValueError(_SNR_OFFSET_HINT)
        er_lambdas: list[float] = []
        for sigma in sigmas:
            if sigma == 0:
                er_lambdas.append(0.0)
                continue
            if sigma < 0 or (flow and sigma >= 1):
                raise ValueError("er_sde degenerate schedule: sigma outside half-logSNR domain")
            value = math.exp(-_half_log_snr(sigma, flow=flow))
            if not math.isfinite(value):
                raise ValueError("er_sde degenerate schedule: non-finite ER lambda")
            er_lambdas.append(value)

        old_denoised: TensorT | None = None
        old_denoised_d: TensorT | None = None
        s_noise_eff = s_noise * info.noise_scale
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            denoised = denoiser(x, sigmas[i])
            _emit(on_step, info, i, n, sigmas[i], x, denoised)
            if sigmas[i + 1] == 0:
                x = denoised
                old_denoised = denoised
                continue
            ls, lt = er_lambdas[i], er_lambdas[i + 1]
            if ls == 0 or lt == 0:
                raise ValueError("er_sde degenerate schedule: zero ER lambda")
            alpha_s, alpha_t = sigmas[i] / ls, sigmas[i + 1] / lt
            scaled_s, scaled_t = scale(ls), scale(lt)
            if not all(math.isfinite(v) for v in (alpha_s, alpha_t, scaled_s, scaled_t)):
                raise ValueError("er_sde degenerate math: non-finite alpha or noise scaler")
            if scaled_s == 0 or scaled_t == 0:
                raise ValueError("er_sde degenerate math: noise scaler returned zero")
            r = scaled_t / scaled_s
            x = x * (alpha_t / alpha_s * r) + denoised * (alpha_t * (1 - r))

            stage_used = min(max_stage, i + 1)
            if stage_used >= 2:
                assert old_denoised is not None
                dt = lt - ls
                previous_dt = ls - er_lambdas[i - 1]
                if dt == 0 or previous_dt == 0:
                    raise ValueError("er_sde degenerate schedule: repeated ER lambda")
                step = -dt / 200.0
                positions = (lt + point * step for point in range(200))
                scaled_positions = [(position, scale(position)) for position in positions]
                if any(not math.isfinite(value) or value == 0 for _, value in scaled_positions):
                    raise ValueError("er_sde degenerate math: invalid integration noise scaler")
                integral = sum(1 / value for _, value in scaled_positions) * step
                denoised_d = (denoised - old_denoised) * (1 / previous_dt)
                x = x + denoised_d * (alpha_t * (dt + integral * scaled_t))
                if stage_used >= 3:
                    assert old_denoised_d is not None
                    second_dt = (ls - er_lambdas[i - 2]) / 2
                    if second_dt == 0:
                        raise ValueError("er_sde degenerate schedule: repeated stage-3 ER lambda")
                    integral_u = (
                        sum((position - ls) / value for position, value in scaled_positions) * step
                    )
                    denoised_u = (denoised_d - old_denoised_d) * (1 / second_dt)
                    x = x + denoised_u * (alpha_t * (dt**2 / 2 + integral_u * scaled_t))
                old_denoised_d = denoised_d

            if s_noise_eff > 0:
                radicand = lt**2 - ls**2 * r**2
                if not math.isfinite(radicand) or radicand < 0:
                    raise ValueError("er_sde degenerate math: negative noise variance")
                coefficient = alpha_t * s_noise_eff * math.sqrt(radicand)
                if coefficient != 0:
                    x = x + _require_noise(noise, "er_sde")(sigmas[i], sigmas[i + 1]) * coefficient
            old_denoised = denoised
        return x

    return solve


def seeds_2(
    *, eta: float = 1.0, s_noise: float = 1.0, r: float = 0.5, solver_type: str = "phi_1"
) -> SolverFn[Any]:
    """SEEDS-2 (sample_seeds_2 @ b78cec87)."""
    _check_ancestral_eta(eta)
    if not 0 < r <= 1:
        raise ValueError(f"seeds_2 r must be in (0, 1], got {r}")
    if solver_type not in {"phi_1", "phi_2"}:
        raise ValueError("solver_type must be 'phi_1' or 'phi_2'")

    def solve(
        denoiser: Denoiser[TensorT],
        x: TensorT,
        sigmas: Sequence[float],
        info: SamplerInfo,
        *,
        noise: NoiseSampler[TensorT] | None = None,
        on_step: StepCallback | None = None,
        on_step_begin: Callable[[int], None] | None = None,
    ) -> TensorT:
        flow = is_flow_parameterization(info.parameterization)
        s_noise_eff = s_noise * info.noise_scale
        inject_noise = eta > 0 and s_noise_eff > 0
        n = len(sigmas) - 1
        for i in range(n):
            _begin(on_step_begin, i)
            sigma_s = sigmas[i]
            denoised = denoiser(x, sigma_s)
            _emit(on_step, info, i, n, sigma_s, x, denoised)
            sigma_t = sigmas[i + 1]
            if sigma_t == 0:
                x = denoised
                continue
            if sigma_s <= 0 or (flow and sigma_s >= 1) or (flow and sigma_t >= 1):
                raise ValueError("seeds_2 degenerate schedule: sigma outside half-logSNR domain")
            lambda_s = _half_log_snr(sigma_s, flow=flow)
            lambda_t = _half_log_snr(sigma_t, flow=flow)
            h = lambda_t - lambda_s
            if h == 0:
                raise ValueError("seeds_2 degenerate schedule: repeated half-logSNR")
            h_eta = h * (eta + 1)
            lambda_1 = lambda_s + r * h
            sigma_1 = _sigma_from_half_log_snr(lambda_1, flow=flow)
            alpha_1 = _alpha(sigma_1, lambda_1)
            alpha_t = _alpha(sigma_t, lambda_t)
            x_2 = x * (sigma_1 / sigma_s * math.exp(-r * h * eta)) - denoised * (
                alpha_1 * _phi_1(-r * h_eta)
            )
            sde_noise: TensorT | None = None
            if inject_noise:
                coeff = math.sqrt(max(-math.expm1(-2 * r * h * eta), 0.0))
                sde_noise = _require_noise(noise, "seeds_2")(sigma_s, sigma_1) * coeff
                x_2 = x_2 + sde_noise * (sigma_1 * s_noise_eff)
            denoised_2 = denoiser(x_2, sigma_1)
            if solver_type == "phi_1":
                denoised_d = denoised + (denoised_2 - denoised) * (1 / (2 * r))
                x = x * (sigma_t / sigma_s * math.exp(-h * eta)) - denoised_d * (
                    alpha_t * _phi_1(-h_eta)
                )
            else:
                b2 = _phi_2(-h_eta, "seeds_2") / r
                b1 = _phi_1(-h_eta) - b2
                x = (
                    x * (sigma_t / sigma_s * math.exp(-h * eta))
                    - (denoised * b1 + denoised_2 * b2) * alpha_t
                )
            if inject_noise:
                assert sde_noise is not None
                segment = (r - 1) * h * eta
                sde_noise = sde_noise * math.exp(segment) + _require_noise(noise, "seeds_2")(
                    sigma_1, sigma_t
                ) * math.sqrt(max(-math.expm1(2 * segment), 0.0))
                x = x + sde_noise * (sigma_t * s_noise_eff)
        return x

    return solve


