def __getattr__(name: str) -> _Any:
    try:
        module_name, attribute = _EXPORTS[name]
    except KeyError:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from None
    module = _import_module(f".{module_name}", __name__)
    value = getattr(module, attribute) if attribute is not None else module
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(globals().keys() | _EXPORTS.keys())


class _ExportModule(_ModuleType):
    def __setattr__(self, name: str, value: _Any) -> None:
        # Import machinery binds submodules on their parent after execution.
        # component_publisher is also a function export: submodule-first imports
        # must not replace that function with its module and bypass __getattr__.
        binding = _EXPORTS.get(name)
        if (
            binding is not None
            and binding[1] is not None
            and isinstance(value, _ModuleType)
            and value.__name__ == f"{__name__}.{binding[0]}"
        ):
            value = getattr(value, binding[1])
        super().__setattr__(name, value)


_sys.modules[__name__].__class__ = _ExportModule
