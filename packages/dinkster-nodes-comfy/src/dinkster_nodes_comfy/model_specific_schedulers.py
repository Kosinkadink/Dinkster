class AlignYourStepsScheduler(Node):
    @classmethod
    def define_schema(cls) -> NodeSchema:
        return NodeSchema(
            node_type="AlignYourStepsScheduler",
            search_terms=("AYS scheduler",),
            category="model/sampling/schedulers",
            inputs=(
                InputSpec(
                    "model_type",
                    TypeExpr.concrete(CORE_COMBO),
                    widget=ComboWidget(("SD1", "SDXL", "SVD")),
                ),
                InputSpec(
                    "steps",
                    TypeExpr.concrete(CORE_INT),
                    default=10,
                    widget=NumberWidget(min=1, max=10000),
                ),
                InputSpec(
                    "denoise",
                    TypeExpr.concrete(CORE_FLOAT),
                    default=1.0,
                    widget=NumberWidget(min=0.0, max=1.0, step=0.01),
                ),
            ),
            outputs=(OutputSpec("SIGMAS", TypeExpr.concrete(SIGMAS_TYPE)),),
        )

    @classmethod
    def execute(cls, *, model_type: str, steps: int, denoise: float) -> Mapping[str, object]:
        torch = importlib.import_module("torch")
        total_steps = steps
        if denoise < 1.0:
            if denoise <= 0.0:
                return cls.outputs(SIGMAS=torch.FloatTensor([]))
            total_steps = round(steps * denoise)

        sigmas = AYS_NOISE_LEVELS[model_type][:]
        if (steps + 1) != len(sigmas):
            sigmas = _loglinear_interp(sigmas, steps + 1)

        sigmas = sigmas[-(total_steps + 1) :]
        sigmas[-1] = 0
        return cls.outputs(SIGMAS=torch.FloatTensor(sigmas))


