"""Model-aware sigma schedules ported from ComfyUI @ b78cec87.

AlignYourSteps (comfy_extras/nodes_align_your_steps.py), GITS
(comfy_extras/nodes_gits.py), and OptimalSteps
(comfy_extras/nodes_optimalsteps.py) select sigma sequences from
model-calibrated noise-level tables, log-linearly resampled to the
requested step count. The math runs in float64 numpy exactly like the
reference; results carry the reference's final float32 cast so the
values match ComfyUI's FloatTensor output bit for bit.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np


def _loglinear_interp(t_steps: Sequence[float], num_steps: int) -> list[float]:
    """Log-linear resampling of a decreasing sequence (loglinear_interp
    @ b78cec87)."""
    xs = np.linspace(0, 1, len(t_steps))
    ys = np.log(np.asarray(t_steps, dtype=np.float64)[::-1])
    new_xs = np.linspace(0, 1, num_steps)
    new_ys = np.interp(new_xs, xs, ys)
    return [float(value) for value in np.exp(new_ys)[::-1]]


def _finish_sigmas(sigmas: list[float], total_steps: int) -> tuple[float, ...]:
    """Keep the last total_steps+1 levels, zero the tail, cast float32."""
    kept = sigmas[-(total_steps + 1) :]
    kept[-1] = 0.0
    return tuple(float(value) for value in np.asarray(kept, dtype=np.float32))


def _denoise_steps(steps: int, denoise: float) -> int | None:
    """Effective step count under partial denoise; None means empty sigmas."""
    if denoise < 1.0:
        if denoise <= 0.0:
            return None
        return round(steps * denoise)
    return steps


def _tabled_sigmas(levels: Sequence[float], steps: int, denoise: float) -> tuple[float, ...]:
    total_steps = _denoise_steps(steps, denoise)
    if total_steps is None:
        return ()
    sigmas = list(levels)
    if (steps + 1) != len(sigmas):
        sigmas = _loglinear_interp(sigmas, steps + 1)
    return _finish_sigmas(sigmas, total_steps)


def align_your_steps_sigmas(model_type: str, steps: int, denoise: float) -> tuple[float, ...]:
    return _tabled_sigmas(ALIGN_YOUR_STEPS_NOISE_LEVELS[model_type], steps, denoise)


def optimal_steps_sigmas(model_type: str, steps: int, denoise: float) -> tuple[float, ...]:
    return _tabled_sigmas(OPTIMAL_STEPS_NOISE_LEVELS[model_type], steps, denoise)


def gits_sigmas(coeff: float, steps: int, denoise: float) -> tuple[float, ...]:
    total_steps = _denoise_steps(steps, denoise)
    if total_steps is None:
        return ()
    rows = GITS_NOISE_LEVELS[round(coeff, 2)]
    if steps <= 20:
        sigmas = list(rows[steps - 2])
    else:
        sigmas = _loglinear_interp(rows[-1], steps + 1)
    return _finish_sigmas(sigmas, total_steps)


