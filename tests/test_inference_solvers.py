def run_case(name: str, descriptor_id: str) -> tuple[Vec, CountingNoise]:
    case = SOLVERS["cases"][name]
    descriptor = builtin_sampler_registry().get(descriptor_id)
    assert descriptor is not None
    solver = descriptor.build(**case["options"])
    noise = CountingNoise()
    x = Vec(tuple(SOLVERS["x0"]))
    sigmas = tuple(SOLVERS["sigmas"][case["space"]])
    if name in OFFSET_CASES:
        sigmas = offset_first_sigma_for_snr(sigmas, FlowSigmas(shift=1.0), flow=True)
    denoiser = CfgMockDenoiser() if descriptor.needs_uncond else mock_denoised
    final = solver(denoiser, x, sigmas, SPACE_INFO[case["space"]], noise=noise)
    return final, noise


class TestSolverGoldens:
    @pytest.mark.parametrize("name", sorted(CASE_DESCRIPTOR))
    def test_final_matches_reference(self, name: str) -> None:
        case = SOLVERS["cases"][name]
        final, noise = run_case(name, CASE_DESCRIPTOR[name])
        # DEIS evaluates 10,000-point transcendental tables with scalar
        # math instead of torch kernels; the observed float64 seam is
        # 5.63e-8, with 7e-8 headroom and identical integration/order math.
        # DPM-fast's reference torch.linspace/transcendentals versus the
        # scalar float64 port drift by at most 2.90e-8; 4e-8 is per-case
        # headroom after the endpoint/order seams were verified exactly.
        # ER-SDE deliberately mirrors the reference's float32 integration
        # grid with scalar math; its measured seam is 7.49e-9, with 1.3e-8
        # headroom and identical stage/noise equations.
        # UniPC's portable torch-free solver deliberately evaluates the
        # reference's float32 tensor coefficients and linear solves as
        # Python float64 scalar math. Its 2e-5 band covers that proven
        # portable/reference arithmetic seam; torch runtimes replace it
        # with the exact reference-kernel override.
        abs_tol = (
            2e-5
            if name.startswith("uni_pc")
            else 4e-8
            if name.startswith("dpm_fast_")
            else 7e-8
            if name.startswith("deis_")
            else 1.3e-8
            if name.startswith("er_sde_")
            else ABS
        )
        for i, (ours, ref) in enumerate(zip(final.values, case["final"], strict=True)):
            assert math.isclose(ours, ref, rel_tol=REL, abs_tol=abs_tol), (
                f"{name} index {i}: {ours} != {ref}"
            )
        expected_draws = PORT_DRAWS_OVERRIDE.get(name, case["noise_draws"])
        assert len(noise.calls) == expected_draws, (
            f"{name}: {len(noise.calls)} draws != {expected_draws}"
        )

