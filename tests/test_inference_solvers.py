        for sampler_id, descriptor in first.items():
            other = second[sampler_id]
            assert descriptor is not other
            assert descriptor == other
            if descriptor.options:
                assert descriptor.options is not other.options
                for spec, other_spec in zip(descriptor.options, other.options, strict=True):
                    assert spec is not other_spec
                    assert spec == other_spec

