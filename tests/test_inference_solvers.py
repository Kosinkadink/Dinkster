class TestCancellationTrust:
    """Distributed receipt admission executes the ambient cancellation
    between solver steps, so only cancellation that provably runs no
    caller code is trusted: the default no-op or the exact set-only
    CancellationFlag."""

    def test_flag_is_a_set_only_latch(self) -> None:
        from dinkster_inference import CancellationFlag

        flag = CancellationFlag()
        assert flag() is False
        flag.cancel()
        assert flag() is True
        with pytest.raises(AttributeError):
            flag.check = lambda: False  # type: ignore[attr-defined]

    def test_trust_covers_exactly_the_no_op_and_the_flag(self) -> None:
        from dinkster_inference import (
            CancellationFlag,
            sampling_cancellation_is_trusted,
            use_sampling_environment,
        )

        assert sampling_cancellation_is_trusted()
        with use_sampling_environment((), CancellationFlag()):
            assert sampling_cancellation_is_trusted()
        with use_sampling_environment((), lambda: False):
            assert not sampling_cancellation_is_trusted()

        class FlagAlike(CancellationFlag):  # pyright: ignore[reportGeneralTypeIssues]
            def __call__(self) -> bool:
                raise AssertionError("subclass code must never be trusted")

        subclassed = FlagAlike()
        with use_sampling_environment((), subclassed):
            assert not sampling_cancellation_is_trusted()

    def test_planted_slot_value_never_executes(self) -> None:
        """The slot is writable, so a foreign object planted there must
        read as not cancelled without its __bool__ ever running."""
        from dinkster_inference import CancellationFlag, CancellationToken

        executed: list[str] = []

        class Evil:
            def __bool__(self) -> bool:
                executed.append("executed")
                return False

        flag = CancellationFlag()
        flag._cancelled = Evil()  # type: ignore[assignment]
        result = flag()
        assert result is False
        CancellationToken(flag).check()
        assert executed == []
