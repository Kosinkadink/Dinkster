    def test_catalogs_reconstruct_fresh_descriptors_per_call(self) -> None:
        """Each catalog call builds new descriptor objects from deep
        snapshots captured at import: the published descriptor constants
        are caller-reachable and mutable via ``object.__setattr__``, so
        no shared instance - descriptor or nested container - may double
        as the admission trust root. Fresh constructions stay
        behaviorally canonical (catalog_value_is_canonical), with
        behavior-bearing functions identical across calls."""
        from dataclasses import fields as dataclass_fields

        from dinkster_inference import catalog_value_is_canonical

        for first, second in (
            (builtin_samplers(), builtin_samplers()),
            (builtin_schedulers(), builtin_schedulers()),
        ):
            assert len(first) == len(second)
            for left, right in zip(first, second, strict=True):
                assert left is not right
                assert type(left) is type(right)
                names = {item.name for item in dataclass_fields(left)}
                assert set(vars(left)) == set(vars(right)) == names
                for name in names:
                    left_value = getattr(left, name)
                    right_value = getattr(right, name)
                    assert catalog_value_is_canonical(left_value, right_value)
                    if callable(left_value):
                        assert left_value is right_value
                    elif type(left_value) is tuple and left_value:
                        assert left_value is not right_value

