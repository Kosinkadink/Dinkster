def mock_denoised(x: Vec, sigma: float) -> Vec:
    """Twin of the generator's solver_mock_denoised: nonlinear in x so
    coefficient errors cannot cancel."""
    return x * (1.0 / (1.0 + sigma)) + (x * x) * (0.05 / (1.0 + sigma))


def mock_uncond(x: Vec, sigma: float) -> Vec:
    """Twin of the generator's solver_mock_uncond: a second, distinct
    nonlinear formula so the CFG++ solvers' combined/uncond channels
    cannot be confused."""
    return x * (0.8 / (1.2 + sigma)) - (x * x) * (0.03 / (1.0 + sigma))


class CfgMockDenoiser:
    """Twin of the generator's _MockCfgModel: a denoiser carrying the
    UncondDenoiser capability, returning the same combined/uncond pair
    the reference's post-CFG hook chain hands the cfg_pp solvers."""

    def __call__(self, x: Vec, sigma: float) -> Vec:
        return mock_denoised(x, sigma)

    def call_with_uncond(self, x: Vec, sigma: float) -> tuple[Vec, Vec]:
        return mock_denoised(x, sigma), mock_uncond(x, sigma)


@dataclass
class CountingNoise:
    """Twin of the generator's counter-based draw: deterministic values
    per draw index, recording call arguments."""

    calls: list[tuple[float, float]] = field(default_factory=list)

    def __call__(self, sigma_from: float, sigma_to: float) -> Vec:
        k = len(self.calls)
        self.calls.append((sigma_from, sigma_to))
        return Vec(tuple(math.sin(1.3 * k + 0.7 * j + 0.1) for j in range(DIMS)))


