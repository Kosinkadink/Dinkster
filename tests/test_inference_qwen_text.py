def test_ovis_and_txt_norm_workloads_name_exact_vector_free_trigger() -> None:
    workload = next(
        item for item in WORKLOADS["workloads"] if item["id"] == "W0-FLUX-GATED-OVIS-TXT2IMG"
    )
    assert workload["provenance"]["fired_trigger"] == ("W0-FLUX-VECTOR-FREE landed at 272e842")
    assert set(workload["provenance"]["discharged_deferrals"]) == {
        "W0-FLUX-GATED-OVIS-TWO-PHASE",
        "W0-FLUX-TXT-NORM-TWO-PHASE",
    }
    artifacts = {item["role"]: item for item in workload["artifacts"]}
    diffusion_layout = artifacts["ovis-vector-free-gated-txt-norm-flux-diffusion"]["layout"]
    assert diffusion_layout["text_input"] == "txt_in.weight [3072, 2048]"
    assert diffusion_layout["text_normalization"] == "txt_norm.scale [2048]"
    assert diffusion_layout["vector_input"] == "absent"
    assert diffusion_layout["guidance_input"] == "absent"
    component_ids = {item["id"] for item in WORKLOADS["component_artifacts"]}
    assert not component_ids.intersection(
        {"ovis-2.5-qwen3-2b-text", "ovis-image-bf16-diffusion", "flux-ae-kl-codec"}
    )
    assert WORKLOADS["deferred_workloads"] == []
    longcat = {item["id"]: item for item in WORKLOADS["component_artifacts"]}
    diffusion = longcat["longcat-image-bf16-diffusion"]
    text = longcat["longcat-qwen-2.5-vl-7b-fp8-text"]
    assert diffusion["status"] == "accepted-component-layout"
    assert text["status"] == "accepted-component-layout"
    assert "deferral" not in diffusion
    assert "deferral" not in text
    assert diffusion["follow_up_deferral"] == text["follow_up_deferral"]
    assert diffusion["follow_up_deferral"]["name"] == "W0-LONGCAT-EXECUTION"
    expected_provenance = {
        "download_date": "2026-07-30",
        "template_commit": "aa3661d9fc1a493f8de6b029f5b8af27da3c5d08",
        "template_digest": (
            "sha256:30f5a89de5e516a36b47d7bbb912c6901079064ba4f9b31bcda43188103450a4"
        ),
        "upstream_reference_commit": "9cf91339b708a245762fa38ffeec9702b381e0db",
        "verified_on": "RipperPC",
    }
    assert diffusion["provenance"] == expected_provenance
    assert text["provenance"] == expected_provenance

    diffusion_layout = diffusion["layout"]
    assert diffusion_layout["key_count"] == 412
    assert diffusion_layout["dtype"] == "bfloat16"
    assert diffusion_layout["text_input"] == "txt_in.weight [3072, 3584]"
