"""Exact Ovis Qwen3-2B header and prompt-policy closure.

The golden is generated by executing ComfyUI at b78cec87 through
tools/gen_ovis_text_goldens.py. It pins the full model layout and the
fixed-template tokenizer behavior, including disabled prompt weights,
right padding, attention masks, and the post-template slice marker.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import pytest
from dinkster_inference import (
    BFLOAT16,
    OVIS_QWEN3_2B_CONFIG,
    QwenTextDetectError,
    TensorGeometry,
    detect_qwen_text_config,
    qwen_text_layout,
    tokenize_ovis_prompt,
)

GOLDENS = json.loads((Path(__file__).parent / "goldens" / "ovis_text_goldens.json").read_text())
WORKLOADS = json.loads(
    (Path(__file__).parent.parent / "tools" / "inference_parity" / "workloads.json").read_text()
)


def exact_geometries() -> dict[str, TensorGeometry]:
    return {key: TensorGeometry(tuple(shape), BFLOAT16) for key, shape in GOLDENS["layout"]}


def test_full_layout_matches_executed_reference() -> None:
    expected = [(key, tuple(shape)) for key, shape in GOLDENS["layout"]]
    assert sorted(qwen_text_layout(OVIS_QWEN3_2B_CONFIG).items()) == expected
    assert detect_qwen_text_config(exact_geometries()) is OVIS_QWEN3_2B_CONFIG


def test_wrong_width_refuses() -> None:
    geometries = exact_geometries()
    geometries["embed_tokens.weight"] = TensorGeometry((151936, 3584), BFLOAT16)
    with pytest.raises(QwenTextDetectError, match="unknown Qwen text width"):
        detect_qwen_text_config(geometries)


def test_wrong_role_refuses() -> None:
    with pytest.raises(QwenTextDetectError, match="not a Qwen text-model role"):
        detect_qwen_text_config(
            {"vision_model.patch_embed.weight": TensorGeometry((8, 8), BFLOAT16)}
        )


def test_missing_or_extra_model_key_refuses_strictly() -> None:
    missing = exact_geometries()
    del missing["layers.27.mlp.down_proj.weight"]
    with pytest.raises(QwenTextDetectError, match="missing layers.27"):
        detect_qwen_text_config(missing)

    extra = exact_geometries()
    extra["lm_head.weight"] = TensorGeometry((151936, 2048), BFLOAT16)
    with pytest.raises(QwenTextDetectError, match="unexpected key lm_head.weight"):
        detect_qwen_text_config(extra)


@pytest.mark.parametrize("case", GOLDENS["tokenizer"], ids=lambda case: case["text"])
def test_tokenizer_matches_executed_reference(case: dict[str, Any]) -> None:
    got = tokenize_ovis_prompt(str(case["text"]))
    assert list(got.ids) == case["ids"]
    assert list(got.attention_mask) == case["attention_mask"]
    assert set(case["weights"]) == {1.0}


def test_template_padding_mask_and_post_template_slice() -> None:
    tokens = tokenize_ovis_prompt("cat")
    assert len(tokens.ids) == OVIS_QWEN3_2B_CONFIG.min_tokens == 284
    assert tokens.ids[-1] == OVIS_QWEN3_2B_CONFIG.pad_token_id
    assert tokens.attention_mask[-1] == 0
    assert tokens.ids[tokens.slice_start - 1 : tokens.slice_start + 1] == (4004, 25)
    assert tokens.slice_start == 28


def test_prompt_weight_syntax_is_literal() -> None:
    plain = tokenize_ovis_prompt("cat")
    weighted_syntax = tokenize_ovis_prompt("(cat:2.0)")
    assert plain.ids != weighted_syntax.ids
    case = next(item for item in GOLDENS["tokenizer"] if item["text"] == "(cat:2.0)")
    assert set(case["weights"]) == {1.0}


def test_escaped_parentheses_and_embedding_boundaries_match_reference() -> None:
    for text in (r"\(cat:1.2\)", "a embedding:foo"):
        case = next(item for item in GOLDENS["tokenizer"] if item["text"] == text)
        assert list(tokenize_ovis_prompt(text).ids) == case["ids"]


def test_literal_pad_token_starts_reference_attention_masking() -> None:
    tokens = tokenize_ovis_prompt("<|endoftext|> masked tail")
    first_pad = tokens.ids.index(OVIS_QWEN3_2B_CONFIG.pad_token_id)
    assert tokens.attention_mask[first_pad - 1 : first_pad + 2] == (1, 0, 0)


def test_vendored_tokenizer_is_deterministic() -> None:
    first = tokenize_ovis_prompt("cafe\u0301 \u4e2d")
    second = tokenize_ovis_prompt("cafe\u0301 \u4e2d")
    assert first == second


def test_adversarial_tokenizer_corpus_matches_executed_reference() -> None:
    outputs = [
        [list(tokenize_ovis_prompt(str(text)).ids)]
        for text in GOLDENS["tokenizer_corpus"]["prompts"]
    ]
    canonical = json.dumps(outputs, separators=(",", ":")).encode("ascii")
    assert (
        hashlib.sha256(canonical).hexdigest() == (GOLDENS["tokenizer_corpus"]["token_ids_sha256"])
    )


