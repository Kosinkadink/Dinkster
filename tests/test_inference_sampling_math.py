class TestSigmaSpaces:
    def test_checkpoint_bounded_continuous_edm_matches_executed_golden(
        self,
    ) -> None:
        bounds = EDM_VPRED_GOLDENS["bounds"]
        golden = EDM_VPRED_GOLDENS["space"]
        space = ContinuousEDMSigmas(min_sigma=bounds["sigma_min"], max_sigma=bounds["sigma_max"])
        table = space.table
        assert table is not None
        seq_close(table[:3], golden["table_head"])
        assert close(table[len(table) // 2], golden["table_mid"])
        seq_close(table[-3:], golden["table_tail"])
        for timestep, sigma in golden["sigma_of_t"].items():
            assert close(space.sigma(float(timestep)), sigma)
        for sigma, timestep in golden["timestep_of_sigma"].items():
            assert close(space.timestep(float(sigma)), timestep)

    @pytest.mark.parametrize(
        ("sigma_min", "sigma_max"),
        ((float("nan"), 1.0), (0.1, float("inf")), (2.0, 1.0)),
    )
    def test_continuous_edm_rejects_invalid_bounds(
        self, sigma_min: float, sigma_max: float
    ) -> None:
        with pytest.raises(ValueError):
            ContinuousEDMSigmas(min_sigma=sigma_min, max_sigma=sigma_max)

    @pytest.mark.parametrize("name", list(spaces_under_test()))
    def test_endpoints_match_reference(self, name: str) -> None:
        space = spaces_under_test()[name]
        ref: dict[str, Any] = GOLDENS["spaces"][name]
        assert close(space.sigma_min, ref["sigma_min"])
        assert close(space.sigma_max, ref["sigma_max"])

    @pytest.mark.parametrize("name", list(spaces_under_test()))
    def test_table_matches_reference(self, name: str) -> None:
        space = spaces_under_test()[name]
        ref: dict[str, Any] = GOLDENS["spaces"][name]
        table = space.table
        assert table is not None
        assert len(table) == ref["table_len"]
        seq_close(table[:3], ref["table_head"])
        seq_close(table[-3:], ref["table_tail"])
        assert close(table[len(table) // 2], ref["table_mid"])

    @pytest.mark.parametrize("name", list(spaces_under_test()))
    def test_sigma_of_t_matches_reference(self, name: str) -> None:
        space = spaces_under_test()[name]
        for t_str, ref_sigma in GOLDENS["spaces"][name]["sigma_of_t"].items():
            assert close(space.sigma(float(t_str)), ref_sigma), t_str

    @pytest.mark.parametrize("name", list(spaces_under_test()))
    def test_timestep_of_sigma_matches_reference(self, name: str) -> None:
        space = spaces_under_test()[name]
        ref = GOLDENS["spaces"][name]["timestep_of_sigma"]
        for sigma_repr, ref_t in ref.items():
            got = space.timestep(float(sigma_repr))
            # Discrete argmin returns an integer index; allow it exact.
            if isinstance(space, DiscreteSigmas):
                assert got == ref_t, sigma_repr
            else:
                assert close(got, ref_t, rel=1e-5), sigma_repr

    @pytest.mark.parametrize("name", list(spaces_under_test()))
    def test_percent_to_sigma_matches_reference(self, name: str) -> None:
        space = spaces_under_test()[name]
        ref = GOLDENS["spaces"][name]["percent_to_sigma"]
        for p_str, ref_sigma in ref.items():
            assert close(space.percent_to_sigma(float(p_str)), ref_sigma), p_str

    def test_percent_zero_sentinel(self) -> None:
        assert DiscreteSigmas.linear_beta().percent_to_sigma(0.0) == (SIGMA_PERCENT_ZERO)
        assert FlowSigmas(shift=3.0).percent_to_sigma(0.0) == 1.0

    def test_discrete_matches_stage2_catalog_constants(self) -> None:
        space = DiscreteSigmas.linear_beta()
        assert math.isclose(space.sigma_min, SD15.sampling.sigma_min, rel_tol=1e-12)
        assert math.isclose(space.sigma_max, SD15.sampling.sigma_max, rel_tol=1e-12)

    def test_discrete_table_validation(self) -> None:
        with pytest.raises(ValueError, match="ascending"):
            DiscreteSigmas((2.0, 1.0))
        with pytest.raises(ValueError, match="positive"):
            DiscreteSigmas((-1.0, 1.0))
        with pytest.raises(ValueError, match="at least 2"):
            DiscreteSigmas((1.0,))

    def test_shift_helpers_match_reference(self) -> None:
        for key, ref in GOLDENS["shift_fns"]["time_snr_shift"].items():
            alpha, t = (float(v) for v in key.split(","))
            assert close(time_snr_shift(alpha, t), ref)
        for key, ref in GOLDENS["shift_fns"]["flux_time_shift"].items():
            mu, t = (float(v) for v in key.split(","))
            assert close(flux_time_shift(mu, 1.0, t), ref)

