# float32 storage in the reference vs float64 here.
REL = 3e-6


def close(a: float, b: float, rel: float = REL) -> bool:
    return math.isclose(a, b, rel_tol=rel, abs_tol=1e-7)


def seq_close(ours: tuple[float, ...], ref: list[float], rel: float = REL) -> None:
    assert len(ours) == len(ref), f"length {len(ours)} != {len(ref)}"
    for i, (a, b) in enumerate(zip(ours, ref, strict=True)):
        assert close(a, b, rel), f"index {i}: {a} != {b}"


@dataclass(frozen=True)
class Vec:
    """A minimal ArithTensor: elementwise math over a float tuple."""

    values: tuple[float, ...]

    def _lift(self, other: Vec | float) -> tuple[float, ...]:
        if isinstance(other, Vec):
            return other.values
        return tuple(other for _ in self.values)

    def __add__(self, other: Vec | float) -> Vec:
        return Vec(tuple(a + b for a, b in zip(self.values, self._lift(other), strict=True)))

    def __sub__(self, other: Vec | float) -> Vec:
        return Vec(tuple(a - b for a, b in zip(self.values, self._lift(other), strict=True)))

    def __mul__(self, other: Vec | float) -> Vec:
        return Vec(tuple(a * b for a, b in zip(self.values, self._lift(other), strict=True)))

    def __truediv__(self, other: Vec | float) -> Vec:
        return Vec(tuple(a / b for a, b in zip(self.values, self._lift(other), strict=True)))

    def clamp(self, minimum: float, maximum: float, /) -> Vec:
        return Vec(tuple(min(max(v, minimum), maximum) for v in self.values))

    def std(self) -> float:
        mean = sum(self.values) / len(self.values)
        return math.sqrt(sum((v - mean) ** 2 for v in self.values) / (len(self.values) - 1))

    def abs(self) -> Vec:
        return Vec(tuple(abs(v) for v in self.values))

    def maximum(self, other: Vec | float, /) -> Vec:
        lifted = self._lift(other)
        return Vec(tuple(max(a, b) for a, b in zip(self.values, lifted, strict=True)))

    def numel(self) -> int:
        return len(self.values)

    def sum(self) -> float:
        return sum(self.values)


