class TestCfgDenoiser:
    """CfgDenoiser owns cond/uncond branching so evaluators stay
    single-conditioning: one call at cfg 1 or without uncond, two calls
    plus cfg_combine otherwise."""

    @staticmethod
    def _recording_evaluate(
        calls: list[tuple[float, str]],
    ) -> Any:
        def evaluate(x: Vec, sigma: float, conditioning: str) -> Vec:
            calls.append((sigma, conditioning))
            return x * (2.0 if conditioning == "cond" else 0.5)

        return evaluate

    def test_no_uncond_evaluates_cond_once_and_returns_it_untouched(self) -> None:
        calls: list[tuple[float, str]] = []
        denoiser = CfgDenoiser(self._recording_evaluate(calls), "cond", None, 7.5)
        got = denoiser(Vec((1.0, -2.0)), 0.7)
        assert calls == [(0.7, "cond")]
        assert got.values == (2.0, -4.0)

    def test_scale_one_skips_uncond_evaluation(self) -> None:
        calls: list[tuple[float, str]] = []
        denoiser = CfgDenoiser(self._recording_evaluate(calls), "cond", "uncond", 1.0)
        got = denoiser(Vec((1.0, -2.0)), 0.7)
        assert calls == [(0.7, "cond")]
        assert got.values == (2.0, -4.0)

    def test_cfg_runs_cond_then_uncond_and_combines(self) -> None:
        calls: list[tuple[float, str]] = []
        denoiser = CfgDenoiser(self._recording_evaluate(calls), "cond", "uncond", 3.0)
        got = denoiser(Vec((1.0, -2.0)), 0.7)
        assert calls == [(0.7, "cond"), (0.7, "uncond")]
        expected = cfg_combine(Vec((2.0, -4.0)), Vec((0.5, -1.0)), 3.0)
        assert got.values == expected.values


