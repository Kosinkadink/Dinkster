def exact_geometries() -> dict[str, TensorGeometry]:
    return {key: TensorGeometry(shape, BFLOAT16) for key, shape in krea2_text_layout().items()}


def test_krea2_text_config_is_exact_pinned_and_immutable() -> None:
    config = KREA2_TEXT_CONFIG
    assert config == Krea2TextConfig()
    assert (
        config.architecture,
        config.vocab_size,
        config.hidden_size,
        config.intermediate_size,
        config.num_hidden_layers,
        config.num_attention_heads,
        config.num_key_value_heads,
        config.head_dim,
        config.max_position_embeddings,
    ) == ("krea2_qwen3vl_4b", 151936, 2560, 9728, 36, 32, 8, 128, 262144)
    assert (config.rms_norm_eps, config.rope_theta) == (1e-6, 5_000_000.0)
    assert config.rope_dims == (24, 20, 20)
    assert config.interleaved_mrope is True
    assert config.qkv_bias is False
    assert (config.qk_norm, config.final_norm) == (True, True)
    assert config.tap_layers == KREA2_TAP_LAYERS
    assert config.stack_width == 12 * 2560 == 30720
    assert (
        config.pad_token_id,
        config.im_start_token_id,
        config.user_token_id,
        config.newline_token_id,
    ) == (151643, 151644, 872, 198)
    with pytest.raises(FrozenInstanceError):
        config.hidden_size = 1  # type: ignore[misc]
    with pytest.raises(ValueError, match="exact Krea 2 profile"):
        replace(config, hidden_size=1)
    with pytest.raises(ValueError, match="exact Krea 2 profile"):
        replace(config, qkv_bias=0)  # type: ignore[arg-type]


